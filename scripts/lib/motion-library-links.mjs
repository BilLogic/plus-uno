/**
 * Derives Storybook docs links for Motion · Library rows from MDX pages that
 * render `<MotionSection component="..." [tier="..."] />`.
 *
 * Pure over page text (`deriveMotionLibraryLinksFromPages`), with
 * `deriveMotionLibraryLinks` reading the repo's MDX and story titles through
 * `scanStorybookPages` so `<Meta title="...">` and `<Meta of={XStories} />`
 * both resolve with nothing hand-listed.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { scanStorybookPages } from './storybook-pages.mjs';
import { motionRowOf } from './tokens/motion-docs.mjs';
import { MOTION_REGISTRY } from './tokens/motion-registry.mjs';

const DEFAULT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** Matches `.storybook/docs-toc.jsx` `stampHeadingIds` slugging for plain MDX headings. */
function headingSlug(raw) {
  const plain = raw
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');
  return (
    plain
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'section'
  );
}

/** Matches `FoundationSection` slugging in `design-system/src/storybook-docs/foundation-page.jsx`. */
function foundationSlug(title) {
  return title
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function maskCodeFences(source) {
  return source.replace(/```[\s\S]*?```/g, (block) =>
    block
      .split('\n')
      .map((line) => ' '.repeat(line.length))
      .join('\n'),
  );
}

function attrOf(attrs, name) {
  for (const m of attrs.matchAll(/([A-Za-z0-9_-]+)=["']([^"']+)["']/g)) {
    if (m[1] === name) return m[2];
  }
  return null;
}

function anchorsInPage(masked) {
  const anchors = [];
  const taken = new Set();

  for (const m of masked.matchAll(/<FoundationSection(?:\s[^>]*|)>/g)) {
    const explicit = attrOf(m[0], 'id');
    const title = attrOf(m[0], 'title') ?? '';
    const id = `foundation-${explicit ?? foundationSlug(title)}`;
    taken.add(id);
    anchors.push({ index: m.index, id });
  }

  for (const m of masked.matchAll(/^(#{2,6})\s+(.+?)(?:\s*\{#([a-z0-9-]+)\})?\s*$/gm)) {
    let id = m[3] ?? headingSlug(m[2]);
    if (!m[3]) {
      const base = id;
      for (let n = 2; taken.has(id); n += 1) id = `${base}-${n}`;
    }
    taken.add(id);
    anchors.push({ index: m.index, id });
  }

  return anchors.sort((a, b) => a.index - b.index);
}

function activeDocsTabAt(masked, index) {
  const before = masked.slice(0, index);
  const stack = [];
  for (const m of before.matchAll(/<DocsTab(?:\s[^>]*|)>|<\/DocsTab>/g)) {
    if (m[0] === '</DocsTab>') stack.pop();
    else stack.push(attrOf(m[0], 'tab'));
  }
  return stack.at(-1) ?? null;
}

/**
 * Map `{ '<tier>:<name>': '?path=/docs/<docsId>#<anchor>' }` derived from
 * `{ file, docsId, source }[]` MDX pages and a motion registry.
 */
export function deriveMotionLibraryLinksFromPages(pages, registry = MOTION_REGISTRY) {
  const entries = [];

  for (const page of pages) {
    if (!page.file?.endsWith('.mdx') || !page.docsId || typeof page.source !== 'string') continue;
    const masked = maskCodeFences(page.source);
    const anchors = anchorsInPage(masked);

    for (const m of masked.matchAll(/<MotionSection(\s[^>]*|)\/>/g)) {
      const component = attrOf(m[1], 'component');
      if (!component) continue;
      const tier = attrOf(m[1], 'tier');
      const row = motionRowOf(component, registry, tier);
      if (!row) continue;

      const anchor = [...anchors].reverse().find((a) => a.index < m.index)?.id ?? 'motion';
      const tab = activeDocsTabAt(masked, m.index);
      const tabQuery = tab === 'usage' ? '&tab=plus-usage' : '';
      entries.push([`${row.tier}:${row.name}`, `?path=/docs/${page.docsId}${tabQuery}#${anchor}`]);
    }
  }

  entries.sort(([a], [b]) => a.localeCompare(b));
  return Object.fromEntries(entries);
}

/** Scan `repoRoot`'s Storybook MDX pages and derive the `(tier:name) → href` map. */
export function deriveMotionLibraryLinks(repoRoot = DEFAULT_ROOT, registry = MOTION_REGISTRY) {
  const pages = scanStorybookPages(repoRoot)
    .filter((p) => p.file.endsWith('.mdx') && p.docsId)
    .map((p) => ({
      file: p.file,
      docsId: p.docsId,
      source: fs.readFileSync(path.join(repoRoot, p.file), 'utf8'),
    }));
  return deriveMotionLibraryLinksFromPages(pages, registry);
}

/** Render the generated ESM module imported by `scripts/lib/tokens/motion-docs.mjs`. */
export function renderMotionLibraryLinksModule(links) {
  const lines = Object.entries(links)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, href]) => `  ${JSON.stringify(key)}: ${JSON.stringify(href)},`);
  return [
    '// DO NOT EDIT BY HAND. Generated by npm run generate:agent (scripts/generate-motion-library.mjs).',
    'export const MOTION_LIBRARY_LINKS = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}
