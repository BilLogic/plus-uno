#!/usr/bin/env node
// Bakes each design-system component's Storybook docs page into the Worker
// (src/generated/storybook-docs.ts), from `design-system/figma/component-registry.json`.
//
// WHY. uno-bot cannot read Storybook, so a Storybook link it wrote was one it
// built from memory — and a made-up id, in a Figma reply, turned a good answer
// into the can't-find line (#1563). `github_read` now hands back the real docs
// link for a component's files, and this map is where it reads it: the
// registry's `code.storybookId`, which the registry's own generator derives
// from each stories file's title.
//
// WHY BAKED, NOT READ LIVE. The registry is 128 KB, and a turn on Workers Free
// has 50 subrequests (`net.ts`). The deploy chain runs this script before it
// bundles, and the Worker deploys on every push to main, so the map shipped is
// the registry on main at deploy. The committed copy is there for the
// typecheck and the tests; `--check` says whether it still matches.
//
// THE KEYS. A component in a folder of its own (`…/Button/Button.jsx`) owns
// every path in that folder, as `…/Button/`. A component filed flat in its
// group's folder (`…/forms-and-inputs/Checkbox.jsx`) owns the files named for
// it, as `…/forms-and-inputs/Checkbox.` — `Checkbox.mdx`, `Checkbox.stories.jsx`.
//
// Run: npm run generate:storybook-docs  (`-- --check` to compare only)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(process.env.PLUS_UNO_ROOT ?? resolve(HERE, "../../.."));
const REGISTRY = "design-system/figma/component-registry.json";
const OUT = "agents/uno-bot/src/generated/storybook-docs.ts";

/**
 * The map's entries, sorted by key: `[path prefix, component name, Storybook id]`.
 *
 * @param {{ components?: Record<string, { code?: { source?: unknown, storybookId?: unknown } }> }} registry
 * @returns {Array<[string, string, string]>}
 */
export function storybookDocEntries(registry) {
  /** @type {Map<string, [string, string, string]>} */
  const byKey = new Map();
  for (const [name, component] of Object.entries(registry.components ?? {})) {
    const source = component?.code?.source;
    const id = component?.code?.storybookId;
    if (typeof source !== "string" || typeof id !== "string" || !source || !id) continue;
    const dir = posix.dirname(source);
    const stem = posix.basename(source).replace(/\.[^.]+$/, "");
    const key = posix.basename(dir) === stem ? `${dir}/` : `${dir}/${stem}.`;
    // Two components claiming one key would make the link a coin toss: neither gets it.
    if (byKey.has(key)) byKey.set(key, [key, "", ""]);
    else byKey.set(key, [key, name, id]);
  }
  return [...byKey.values()].filter(([, name]) => name).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/**
 * The generated module's text.
 *
 * @param {Array<[string, string, string]>} entries
 */
export function renderStorybookDocs(entries) {
  return (
    "// GENERATED by scripts/generate-storybook-docs.mjs from design-system/figma/component-registry.json\n" +
    "// — do not edit by hand. Run: npm run generate:storybook-docs\n" +
    "// Each entry: [path prefix, component name, Storybook docs id]. Read by src/integrations/storybook-docs.ts.\n" +
    `export const STORYBOOK_DOCS: ReadonlyArray<readonly [string, string, string]> = ${JSON.stringify(entries, null, 2)};\n`
  );
}

function main() {
  const check = process.argv.includes("--check");
  const registry = JSON.parse(readFileSync(resolve(ROOT, REGISTRY), "utf8"));
  const text = renderStorybookDocs(storybookDocEntries(registry));
  const out = resolve(ROOT, OUT);
  const committed = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (check) {
    if (committed !== text) {
      console.error(`${OUT} is stale: run npm run generate:storybook-docs`);
      process.exit(1);
    }
    console.log(`${OUT} is current`);
    return;
  }
  if (committed !== text) writeFileSync(out, text, "utf8");
  console.log(`${OUT}: ${text === committed ? "unchanged" : "written"}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
