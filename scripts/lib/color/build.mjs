/**
 * The color pipeline in one call: plan -> primitive palette -> semantic layer
 * -> SCSS and Figma spec. The reference generator ran these as separate
 * scripts (build, plans, semantics, figma, emit) passing JSON files between
 * them; here they pass values, and nothing touches the disk.
 */

import { emitScss } from './emit.mjs';
import { figmaSpec } from './figma.mjs';
import { PLAN_KEYS, buildPalette, loadPlan } from './plans.mjs';
import { buildSemantics } from './semantics.mjs';

/** One plan, built. Memoized: a plan file does not change within a process. */
const built = new Map();
export function buildPlan(key) {
  if (!built.has(key)) {
    const plan = loadPlan(key);
    built.set(key, { plan, semantics: buildSemantics(buildPalette(plan)) });
  }
  return built.get(key);
}

/** Every plan, built, keyed by plan key. */
export const buildAllPlans = () => Object.fromEntries(PLAN_KEYS.map((key) => [key, buildPlan(key)]));

export const PLAN_FILE = (key) => `scripts/lib/color/plans/plan-${key.toLowerCase()}.json`;

/**
 * The generated files for one plan, rendered and not written.
 *
 * @param {string} key
 * @param {string} generator  repo path of the script that writes them, named in each file's header
 * @returns {Record<string, string>} file name -> contents
 */
export function renderPlan(key, generator) {
  const { semantics } = buildPlan(key);
  const note = `GENERATED by ${generator} from ${PLAN_FILE(key)} (Plan ${key}). Do not edit; change the plan or the generator and run \`npm run generate:color-tokens\`.`;
  const files = emitScss(semantics, `// ${note}\n`);
  files['figma-spec.json'] = `${JSON.stringify({ $generated: note, ...figmaSpec(key, semantics) }, null, 1)}\n`;
  return files;
}
