#!/usr/bin/env node
/**
 * `npm run generate:sound-spec` — the design system's sound-spec module
 * (ADR-043), generated from `scripts/lib/tokens/sound-plan.mjs`.
 *
 * WHAT IT WRITES. `design-system/src/sound/spec.generated.js`: one `SOUND_SPEC`
 * object holding the key, the Detent material, the level tiers, the pickup,
 * the AI count, the output stage and the twelve sound tokens, keyed by name
 * without the `sound.` prefix, and SOUND_MOMENTS from the motion registry.
 * Components and docs share these normalized moment cells.
 *
 * Usage:
 *   node scripts/generate-sound-spec.mjs            # write
 *   node scripts/generate-sound-spec.mjs --check    # CI: fail on drift
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { MOTION_REGISTRY } from './lib/tokens/motion-registry.mjs';
import { isEntry, main } from './lib/findings.mjs';
import { SOUND_AI_COUNT, SOUND_BURST, SOUND_KEY, SOUND_LAND, SOUND_LEVELS, SOUND_MATERIAL, SOUND_NOISE_SECONDS, SOUND_OUTPUT, SOUND_PICKUP, SOUND_SEMANTICS } from './lib/tokens/sound-plan.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const SOUND_SPEC_PATH = 'design-system/src/sound/spec.generated.js';

const NORM = (text) => text.replace(/\r\n/g, '\n');

/** @returns {object} the plan as the runtime reads it: one entry per token, its base pitch resolved to Hz. */
export function soundSpec() {
  const tokens = Object.fromEntries(
    SOUND_SEMANTICS.map(({ name, base, ...token }) => [name, { ...token, base: SOUND_KEY[base].hz }]),
  );
  return { key: SOUND_KEY, material: SOUND_MATERIAL, levels: SOUND_LEVELS, pickup: SOUND_PICKUP, land: SOUND_LAND, burst: SOUND_BURST, noiseSeconds: SOUND_NOISE_SECONDS, aiCount: SOUND_AI_COUNT, output: SOUND_OUTPUT, tokens };
}

/** Sound-bearing registry events, in source order, shared by runtime and docs. */
export function soundMoments(registry = MOTION_REGISTRY) {
  return registry.flatMap((row) => Object.entries(row.events ?? {})
    .filter(([, e]) => e.sound)
    .map(([event, e]) => ({
      row: row.name, tier: row.tier, event, transition: e.transition ?? '',
      token: e.sound.token, at: e.sound.at ?? 'land', when: e.sound.when ?? '',
      spring: e.spatial ?? e.appearance,
    })));
}

/** @returns {string} the generated module's text */
export function soundSpecJs() {
  return `// GENERATED by scripts/generate-sound-spec.mjs from scripts/lib/tokens/sound-plan.mjs (ADR-043).
// Do not edit: run \`npm run generate:sound-spec\`.
// The sound plan as the runtime reads it: tokens keyed by name without the \`sound.\` prefix,
// each token's \`base\` already in Hz.
export const SOUND_SPEC = ${JSON.stringify(soundSpec(), null, 2)};

// Sound moments from scripts/lib/tokens/motion-registry.mjs.
export const SOUND_MOMENTS = ${JSON.stringify(soundMoments(), null, 2)};
`;
}

/** @returns {{path: string, content: string}[]} every file this generator writes, rendered and not written */
export function artifacts() {
  return [{ path: SOUND_SPEC_PATH, content: soundSpecJs() }];
}

/** The drift check. Reports and never writes. */
export function run({ repoRoot = ROOT } = {}) {
  return artifacts()
    .filter(({ path, content }) => {
      const abs = join(repoRoot, path);
      return !existsSync(abs) || NORM(readFileSync(abs, 'utf8')) !== content;
    })
    .map(({ path }) => ({ file: path, message: 'is stale or missing — run: npm run generate:sound-spec' }));
}

export const summary = () => `the sound spec matches the plan (${SOUND_SEMANTICS.length} tokens)`;

if (isEntry(import.meta.url)) {
  if (process.argv.includes('--check')) {
    main(import.meta.url, 'check:sound-spec', { run, summary });
  } else {
    for (const { path, content } of artifacts()) {
      const abs = join(ROOT, path);
      if (existsSync(abs) && NORM(readFileSync(abs, 'utf8')) === content) continue;
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, content);
      console.log(`[write] ${abs}`);
    }
    console.log(`[ok] ${summary()}`);
  }
}
