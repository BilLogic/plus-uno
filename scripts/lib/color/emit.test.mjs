// The emitted mode selectors: light on :root and [data-color-mode="light"],
// dark explicit and under auto, increased contrast override-only for every
// color-mode x contrast-mode combination.
import { test } from 'node:test';
import assert from 'node:assert/strict';

import { renderPlan } from './build.mjs';
import { dsName, paletteVar } from './emit.mjs';

const files = renderPlan('A', 'scripts/generate-color-tokens.mjs');
const selectors = (css) => [...css.matchAll(/^(@media[^{]*|\s*[^\s@][^{\n]*)\{$/gm)].map((m) => m[1].trim());

test('names: --ds- for semantics, --palette- for primitives', () => {
  assert.equal(dsName('color.background.brand.bold'), '--ds-background-brand-bold');
  assert.equal(dsName('elevation.surface.sunken'), '--ds-surface-sunken');
  assert.equal(paletteVar('darkNeutralAlpha.300'), 'var(--palette-dark-neutral-alpha-300)');
  assert.equal(paletteVar('red.500a8'), 'var(--palette-red-500-a8)');
  assert.equal(paletteVar('transparent'), 'transparent');
});

test('every file carries the generated header', () => {
  for (const [file, content] of Object.entries(files)) assert.match(content, /GENERATED by scripts\/generate-color-tokens\.mjs.*Do not edit/, file);
});

const L = ':is([data-color-mode="light"], :not([data-color-mode]))';
const MODE_SELECTORS = [
    '[data-color-mode="light"]', // after ":root,"
    '[data-color-mode="dark"]',
    '@media (prefers-color-scheme: dark)', '[data-color-mode="auto"]',
    `${L}[data-contrast-mode="more"]`,
    '@media (prefers-contrast: more)', `${L}[data-contrast-mode="auto"]`,
    '@media (prefers-color-scheme: light)', '[data-color-mode="auto"][data-contrast-mode="more"]',
    '@media (prefers-color-scheme: light) and (prefers-contrast: more)', '[data-color-mode="auto"][data-contrast-mode="auto"]',
    '[data-color-mode="dark"][data-contrast-mode="more"]',
    '@media (prefers-contrast: more)', '[data-color-mode="dark"][data-contrast-mode="auto"]',
    '@media (prefers-color-scheme: dark)', '[data-color-mode="auto"][data-contrast-mode="more"]',
    '@media (prefers-color-scheme: dark) and (prefers-contrast: more)', '[data-color-mode="auto"][data-contrast-mode="auto"]',
];

test('_semantic.scss selector structure: light, dark, auto dark, and all 8 increased-contrast combinations', () => {
  const sem = files['_semantic.scss'];
  assert.deepEqual(selectors(sem), MODE_SELECTORS);
  assert.match(sem, /^:root,\n\[data-color-mode="light"\] \{$/m);
  assert.equal((sem.match(/color-scheme: dark;/g) ?? []).length, 2);
});

test('light and dark carry all 536 tokens; increased contrast only the rows it changes', () => {
  const sem = files['_semantic.scss'];
  const blocks = sem.split(/\n(?=\S)/).map((b) => (b.match(/--ds-[\w-]+:/g) ?? []).length).filter(Boolean);
  assert.deepEqual(blocks.slice(0, 3), [536, 536, 536]);
  assert.equal(blocks[3], 326); // light IC overrides
  assert.equal(blocks.at(-1), 297); // dark IC overrides
  assert.doesNotMatch(sem, /var\(--ds-[^)]*,/); // no fallbacks
});

test('alphas are rgb() with a slash, never 8-digit hex', () => {
  assert.match(files['_palette.scss'], /--palette-neutral-alpha-300: rgb\(29 27 22 \/ 0\.078\);/);
  assert.doesNotMatch(files['_palette.scss'] + files['_elevation.scss'], /#[0-9a-f]{8}\b/);
});

test('_elevation.scss follows the same switches as _semantic.scss', () => {
  assert.deepEqual(selectors(files['_elevation.scss']), MODE_SELECTORS);
});

