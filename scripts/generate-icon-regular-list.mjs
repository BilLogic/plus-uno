#!/usr/bin/env node
/**
 * `npm run generate:icon-regular-list` — which Font Awesome Free 7.2 icons ship
 * each weight, written to two committed files in `design-system/src/lib/`:
 *
 *   icon-regular.generated.js   the names with a regular weight
 *   icon-free.generated.js      the names Free draws solid, and the brand names
 *
 * `iconClass` (`design-system/src/lib/icon.js`) reads the regular list to pick
 * regular where Free has a glyph and solid where it does not. The design-system
 * lookup and `check:ds-usage` read both files, so no tool needs the Font
 * Awesome package installed. The lists are read from the Font Awesome metadata,
 * never typed by hand: a name is in one when its Free styles include that
 * weight. An alias is not listed, so it draws solid.
 *
 * The metadata is a text file in either shape the package has shipped:
 * `metadata/icons.json` (a `free` list of styles per icon) or
 * `metadata/icon-families.json` (`familyStylesByLicense.free`, as 7.2 ships it).
 * It is read from `node_modules` or the file named by `FA_ICONS_JSON`. Without
 * either, the script leaves the committed lists as they are and says so.
 *
 * Usage:
 *   node scripts/generate-icon-regular-list.mjs          write both files
 *   node scripts/generate-icon-regular-list.mjs --check  fail on a hand edit, or on drift from the metadata when it is here
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { isEntry, main as runCheck } from './lib/findings.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'design-system/src/lib/icon-regular.generated.js';
export const OUT_FREE = 'design-system/src/lib/icon-free.generated.js';
const META = [
  'node_modules/@fortawesome/fontawesome-free/metadata/icons.json',
  'node_modules/@fortawesome/fontawesome-free/metadata/icon-families.json',
];

/** The Free styles of one icon, in either metadata shape. */
const freeStyles = (icon) =>
  icon.free ?? (icon.familyStylesByLicense?.free ?? []).filter((f) => f.family === 'classic').map((f) => f.style);

/** The sorted names whose Free styles include `style`. */
export const namesWith = (icons, style) =>
  Object.entries(icons)
    .filter(([, icon]) => freeStyles(icon).includes(style))
    .map(([name]) => name)
    .sort();

/** The sorted names whose Free styles include regular. */
export const regularNames = (icons) => namesWith(icons, 'regular');

const wrap = (names) => {
  const lines = [];
  let line = '   ';
  for (const name of names) {
    const item = ` "${name}",`;
    if (line.length + item.length > 92) {
      lines.push(line);
      line = '   ';
    }
    line += item;
  }
  lines.push(line);
  return lines.join('\n');
};

/** The module text for a list of names, wrapped at 92 columns. */
export function render(names) {
  return `// GENERATED by scripts/generate-icon-regular-list.mjs from the Font Awesome Free 7.2
// metadata. Do not edit: run \`npm run generate:icon-regular-list\`.
export const FREE_REGULAR_ICONS = new Set([
${wrap(names)}
]);
`;
}

/** The module text for the solid and brands name sets. */
export function renderFree({ solid, brands }) {
  return `// GENERATED by scripts/generate-icon-regular-list.mjs from the Font Awesome Free 7.2
// metadata. Do not edit: run \`npm run generate:icon-regular-list\`.
export const FREE_SOLID_ICONS = new Set([
${wrap(solid)}
]);
export const FREE_BRANDS_ICONS = new Set([
${wrap(brands)}
]);
`;
}

/** Both files' text for parsed metadata. */
export function renderAll(icons) {
  return {
    [OUT]: render(regularNames(icons)),
    [OUT_FREE]: renderFree({ solid: namesWith(icons, 'solid'), brands: namesWith(icons, 'brands') }),
  };
}

/** The names inside `export const <exportName> = new Set([...])`, read as text (the folder is not an ES-module package). */
export function parseSet(text, exportName) {
  const block = text.match(new RegExp(`${exportName} = new Set\\(\\[([^\\]]*)\\]\\)`));
  return block ? [...block[1].matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1]) : [];
}

/** The committed lists, as the sets the lookup and the usage check read. */
export function readCommitted(root = ROOT) {
  const regular = readFileSync(join(root, OUT), 'utf8');
  const free = readFileSync(join(root, OUT_FREE), 'utf8');
  return {
    regular: new Set(parseSet(regular, 'FREE_REGULAR_ICONS')),
    solid: new Set(parseSet(free, 'FREE_SOLID_ICONS')),
    brands: new Set(parseSet(free, 'FREE_BRANDS_ICONS')),
  };
}

const sourceFile = (root = ROOT) => process.env.FA_ICONS_JSON ?? META.map((m) => join(root, m)).find(existsSync);

/** The drift check: a hand edit shows without the metadata, drift from it when the metadata is here. Reports and never writes. */
export function run({ repoRoot = ROOT } = {}) {
  const found = [];
  const fix = 'Run `npm run generate:icon-regular-list`.';
  const committed = { [OUT]: readFileSync(join(repoRoot, OUT), 'utf8'), [OUT_FREE]: readFileSync(join(repoRoot, OUT_FREE), 'utf8') };
  const sets = readCommitted(repoRoot);
  const again = {
    [OUT]: render([...sets.regular]),
    [OUT_FREE]: renderFree({ solid: [...sets.solid], brands: [...sets.brands] }),
  };
  for (const file of Object.keys(committed)) {
    if (committed[file] !== again[file]) found.push({ file, message: `${file} is not in the generated shape (a hand edit). ${fix}` });
  }
  const source = sourceFile(repoRoot);
  if (source && existsSync(source)) {
    const fresh = renderAll(JSON.parse(readFileSync(source, 'utf8')));
    for (const file of Object.keys(fresh)) {
      if (committed[file] !== fresh[file]) found.push({ file, message: `${file} differs from ${source}. ${fix}` });
    }
  }
  return found;
}

/** The green line. */
export function summary({ repoRoot = ROOT } = {}) {
  const sets = readCommitted(repoRoot);
  return `${sets.regular.size} regular, ${sets.solid.size} solid and ${sets.brands.size} brands Free icon names up to date.`;
}

function generate() {
  const source = sourceFile();
  if (!source || !existsSync(source)) {
    console.log('icon-regular-list: no Font Awesome metadata is here (install the package or set FA_ICONS_JSON), so the committed lists stay as they are.');
    return;
  }
  const files = renderAll(JSON.parse(readFileSync(source, 'utf8')));
  for (const [file, text] of Object.entries(files)) writeFileSync(join(ROOT, file), text);
  console.log(`icon-regular-list: ${Object.keys(files).join(' and ')} written`);
}

if (isEntry(import.meta.url)) {
  if (process.argv.includes('--check')) runCheck(import.meta.url, 'check:icon-lists', { run, summary });
  else generate();
}
