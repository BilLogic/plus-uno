import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DS_FACTS_BYTE_BUDGET, bakeFacts, budgetOverrun, generatedDocFor, renderDsFacts } from "./generate-ds-facts.mjs";

/** The facts module's surface, as much of it as the bake reads. */
function fakeFacts() {
  const answers = {
    Button: { kind: "component", import: "import { Button } from '@/components';", group: "forms", source: "x/Button.jsx", summary: null, aliasOf: null, props: [{ name: "appearance", type: "enum", required: false, default: "primary", values: ["primary", "subtle"], description: "long words", deprecated: null }] },
    PatternCard: { kind: "pattern", import: "import { PatternCard } from '@/patterns';", group: "Card", source: "p/PatternCard.jsx", summary: "A raised container.", aliasOf: null, props: null },
  };
  return {
    manifests: {
      components: { components: [{ name: "Button" }, { name: "PatternCard" }] },
      tokens: { tokens: [{ name: "--stack-md", tier: "semantic", group: "Ladder Semantics", value: "var(--space-050)", intent: "Gap between items." }] },
    },
    lookup: (name) => ({ name, status: "exists", ...answers[name] }),
    barrels: { "@/components": new Set(["Button", "BUTTON_SIZES"]), "@/patterns": new Set(["PatternCard"]) },
    retired: new Map([["--stack-xl", "--stack-lg"]]),
  };
}

const INVENTIONS = { components: [{ not: "Card", use: ["PatternCard"], why: "a pattern" }], props: [], tokens: [] };

describe("the baked DS facts", () => {
  it("keeps what the bot answers with and drops prop descriptions and empty fields", () => {
    const baked = bakeFacts(fakeFacts(), { docFor: (name) => (name === "Button" ? "design-system/src/components/forms/Button/index.md" : null), inventions: INVENTIONS });
    assert.deepEqual(baked.components, [
      {
        name: "Button",
        kind: "component",
        import: "import { Button } from '@/components';",
        group: "forms",
        source: "x/Button.jsx",
        doc: "design-system/src/components/forms/Button/index.md",
        props: [{ name: "appearance", type: "enum", values: ["primary", "subtle"], default: "primary" }],
      },
      { name: "PatternCard", kind: "pattern", import: "import { PatternCard } from '@/patterns';", group: "Card", source: "p/PatternCard.jsx", summary: "A raised container." },
    ]);
    assert.deepEqual(baked.barrels, { "@/components": ["BUTTON_SIZES", "Button"], "@/patterns": ["PatternCard"] });
    assert.deepEqual(baked.tokens, [["--stack-md", "semantic", 0, "var(--space-050)", "Gap between items."]]);
    assert.deepEqual(baked.tokenGroups, ["Ladder Semantics"]);
    assert.deepEqual(baked.inventions.components, [{ not: "Card", use: ["PatternCard"], why: "a pattern" }]);
    assert.deepEqual(baked.retired, [["--stack-xl", "--stack-lg"]]);
  });

  it("renders a typed module the Worker imports", () => {
    const text = renderDsFacts(bakeFacts(fakeFacts(), { inventions: INVENTIONS }));
    assert.match(text, /^\/\/ GENERATED by scripts\/generate-ds-facts\.mjs/);
    assert.match(text, /export const DS_FACTS: BakedDsFacts = \{/);
  });

  it("finds a component's generated doc in its own folder or filed flat, and none for a name without one", () => {
    const root = mkdtempSync(join(tmpdir(), "ds-facts-"));
    mkdirSync(join(root, "design-system/src/components/forms/Button"), { recursive: true });
    writeFileSync(join(root, "design-system/src/components/forms/Button/index.md"), "#");
    writeFileSync(join(root, "design-system/src/components/forms/TreeSelect.md"), "#");
    assert.equal(generatedDocFor(root, "Button"), "design-system/src/components/forms/Button/index.md");
    assert.equal(generatedDocFor(root, "TreeSelect"), "design-system/src/components/forms/TreeSelect.md");
    assert.equal(generatedDocFor(root, "Logo"), null);
  });

  it("holds the facts built into the Worker under their byte budget", () => {
    const committed = readFileSync(new URL("../src/generated/ds-facts.ts", import.meta.url), "utf8");
    assert.equal(budgetOverrun(committed), null);
  });

  it("names the overrun in bytes, counting multi-byte characters as bytes", () => {
    assert.equal(budgetOverrun("x".repeat(DS_FACTS_BYTE_BUDGET)), null);
    assert.match(budgetOverrun("x".repeat(DS_FACTS_BYTE_BUDGET + 1)), /1 byte over/);
    assert.match(budgetOverrun("—".repeat(DS_FACTS_BYTE_BUDGET / 3 + 1)), /3 bytes over/);
  });
});
