/**
 * Generate knowledge-audit.md — designer-facing verification spreadsheet.
 *
 * Source of truth: design-system/figma/knowledge-audit.json
 *
 * Usage:
 *   node scripts/generate-knowledge-audit.js
 *   node scripts/generate-knowledge-audit.js --check  (CI: fail if stale, write nothing)
 *
 * The rendered doc is a pure function of knowledge-audit.json, the composition
 * directory listing, and which docs exist. It deliberately carries no
 * generation date and no per-file mtime: both were pure churn — mtime in a
 * fresh clone is the checkout time, identical for every row — and either one
 * would make `--check` fail on the day after it passed, for no reason a
 * designer could act on. A gate that cries wolf daily gets switched off.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { checkArtifacts, writeArtifacts } from './lib/generated-artifact.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const FIGMA_DIR = path.join(REPO_ROOT, 'design-system/figma');
const AUDIT_JSON = path.join(FIGMA_DIR, 'knowledge-audit.json');
const COMPOSITION_DIR = path.join(REPO_ROOT, 'design-system/guidelines/composition');
const OUT_MD = path.join(REPO_ROOT, 'design-system/figma/knowledge-audit.md');

function readJson(fp) {
  return JSON.parse(fs.readFileSync(fp, 'utf8'));
}

function listCompositionFiles() {
  if (!fs.existsSync(COMPOSITION_DIR)) return [];
  return fs.readdirSync(COMPOSITION_DIR)
    .filter((f) => f.endsWith('.md') && f !== 'overview.md')
    .map((f) => `guidelines/composition/${f}`);
}

function mdTable(headers, rows) {
  const sep = headers.map(() => '---');
  const lines = [
    `| ${headers.join(' | ')} |`,
    `| ${sep.join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ];
  return lines.join('\n');
}

function yesNo(v) {
  return v ? '✅ Yes' : '⏳ No';
}

function pathRef(rel) {
  return `\`design-system/${rel}\``;
}

function render() {
  const audit = readJson(AUDIT_JSON);
  const patterns = listCompositionFiles();

  const tokenRows = Object.entries(audit.tokens || {}).map(([file, entry]) => {
    const abs = path.join(REPO_ROOT, 'design-system', file);
    return [
      file,
      pathRef(file),
      fs.existsSync(abs) ? 'yes' : 'no',
      yesNo(!!entry.verified),
      entry.verifiedAt || '—',
      entry.verifiedBy || '—',
      entry.notes || '—',
    ];
  });

  const patternRows = patterns.map((file) => [file, pathRef(file), '—', '—']);

  const doc = `<!-- DO NOT EDIT BY HAND. Generated by npm run generate:agent -->
<!-- Designer workflow: edit design-system/figma/knowledge-audit.json then re-run the script -->

# PLUS Design System — Knowledge Verification Audit

Tracks agent-facing docs and whether a designer has verified them.

Per-component rows are gone: the 56 agent-view skeletons they audited were
deleted in #156. Component documentation is verified in Storybook MDX, and its
generated half returns under #165.

**Edit verification status:** [\`design-system/figma/knowledge-audit.json\`](knowledge-audit.json)

\`\`\`bash
npm run generate:agent
\`\`\`

## Tokens & mapping

${mdTable(
  ['Doc', 'Path', 'On disk', 'Verified', 'Verified at', 'Verified by', 'Notes'],
  tokenRows
)}

## Composition (hand-authored)

${mdTable(['Composition doc', 'Path', 'Verified', 'Notes'], patternRows)}

## How designers verify

1. Compare the doc against Storybook + Figma.
2. Update \`design-system/figma/knowledge-audit.json\`.
3. Run \`npm run generate:agent\`.
`;

  return doc;
}

function main() {
  const check = process.argv.includes('--check');
  const artifacts = [{ file: OUT_MD, content: render() }];

  if (check) {
    if (!checkArtifacts(artifacts)) {
      console.error('  -> run `npm run generate:knowledge-audit`');
      process.exit(1);
    }
    console.log('✓ knowledge-audit.md is up to date');
    return;
  }

  writeArtifacts(artifacts);
}

main();
