#!/usr/bin/env node
/**
 * `npm run generate:icon-regular-list` — which Font Awesome Free 7.2 icons ship
 * a regular weight, written to `design-system/src/lib/icon-regular.generated.js`.
 *
 * `iconClass` (`design-system/src/lib/icon.js`) reads that list to pick regular
 * where Free has a glyph and solid where it does not. The list is read from the
 * Font Awesome metadata, never typed by hand: a name is in it when its `free`
 * styles include `regular`. An alias is not listed, so it draws solid.
 *
 * The metadata is `@fortawesome/fontawesome-free/metadata/icons.json` in
 * `node_modules`, or the file named by `FA_ICONS_JSON`. Without either, the
 * script leaves the committed list as it is and says so.
 *
 * Usage:
 *   node scripts/generate-icon-regular-list.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'design-system/src/lib/icon-regular.generated.js';
const META = 'node_modules/@fortawesome/fontawesome-free/metadata/icons.json';

/** The sorted names whose Free styles include regular. */
export const regularNames = (icons) =>
  Object.entries(icons)
    .filter(([, icon]) => icon.free?.includes('regular'))
    .map(([name]) => name)
    .sort();

/** The module text for a list of names, wrapped at 92 columns. */
export function render(names) {
  const lines = [];
  let line = '   ';
  for (const name of names) {
    const item = ` "${name}",`;
    if (line.length + item.length > 92) {
      lines.push(line);
      line = '   ';
    }
    line += item;
  }
  lines.push(line);
  return `// GENERATED by scripts/generate-icon-regular-list.mjs from the Font Awesome Free 7.2
// metadata. Do not edit: run \`npm run generate:icon-regular-list\`.
export const FREE_REGULAR_ICONS = new Set([
${lines.join('\n')}
]);
`;
}

function main() {
  const source = process.env.FA_ICONS_JSON ?? join(ROOT, META);
  if (!existsSync(source)) {
    console.log(`icon-regular-list: ${META} is not installed here, so the committed list stays as it is.`);
    return;
  }
  const names = regularNames(JSON.parse(readFileSync(source, 'utf8')));
  writeFileSync(join(ROOT, OUT), render(names));
  console.log(`icon-regular-list: ${names.length} names written to ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
