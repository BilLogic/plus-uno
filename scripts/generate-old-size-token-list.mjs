#!/usr/bin/env node
/**
 * `npm run generate:old-size-token-list` — the list of files still on the
 * pre-ADR-038 size vocabularies, written into the spacing guide.
 *
 * The table between the guide's `gen:OLD-SIZE-TOKENS` markers is generated
 * from the same scan `check:old-size-tokens` ratchets
 * (`scripts/check-old-size-tokens.mjs`), so a file leaves it the moment its
 * last old-prefixed `var()` goes.
 *
 * Usage:
 *   node scripts/generate-old-size-token-list.mjs           # write the list
 *   node scripts/generate-old-size-token-list.mjs --check   # CI: fail on drift
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { measure, oldSizeTokenNames, sourcesOf, REPO_ROOT as DEFAULT_ROOT } from './check-old-size-tokens.mjs';
import { isEntry, main } from './lib/findings.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const GUIDE = 'design-system/guidelines/foundations/spacing.md';
const BEGIN = '<!-- gen:OLD-SIZE-TOKENS -->';
const END = '<!-- /gen:OLD-SIZE-TOKENS -->';
const REMEDY = 'Run `npm run generate:old-size-token-list` and commit the guide.';

const scan = (repoRoot = DEFAULT_ROOT) =>
  [...measure(sourcesOf(repoRoot), oldSizeTokenNames()).entries()]
    .map(([file, { count }]) => ({ file, uses: count }))
    .sort((a, b) => b.uses - a.uses || a.file.localeCompare(b.file));

/** The table and its tally, between the markers. */
export function renderList(rows) {
  const uses = rows.reduce((sum, r) => sum + r.uses, 0);
  const lines = [
    `${rows.length} files, ${uses} old-size-token uses. Generated by \`npm run generate:old-size-token-list\`; edit the component files, not this table.`,
    '',
    '| File | Uses |',
    '|---|---:|',
    ...rows.map((r) => `| \`${r.file}\` | ${r.uses} |`),
  ];
  return `${BEGIN}\n${lines.join('\n')}\n${END}`;
}

/** The guide text, and the text it should be (null when the markers are missing). */
export function guideUpdate(text, rows) {
  const current = text.replace(/\r\n/g, '\n');
  const start = current.indexOf(BEGIN);
  const stop = current.indexOf(END);
  if (start < 0 || stop < start) return { current, next: null };
  return { current, next: current.slice(0, start) + renderList(rows) + current.slice(stop + END.length) };
}

const readGuide = (repoRoot) => guideUpdate(readFileSync(join(repoRoot, GUIDE), 'utf8'), scan(repoRoot));

/** The drift check. Reports and never writes. */
export function run({ repoRoot = ROOT } = {}) {
  const { current, next } = readGuide(repoRoot);
  if (next === null) return [{ file: GUIDE, message: `is missing the ${BEGIN} … ${END} markers` }];
  if (next !== current) return [{ file: GUIDE, message: 'the old-size-token list is stale' }];
  return [];
}

export const summary = ({ repoRoot = ROOT } = {}) => `${scan(repoRoot).length} files on old size tokens, listed in ${GUIDE}`;

if (isEntry(import.meta.url)) {
  if (process.argv.includes('--check')) {
    main(import.meta.url, 'check:old-size-token-list', { run, summary, remedy: REMEDY });
  } else {
    const { current, next } = readGuide(ROOT);
    if (next === null) {
      console.error(`✗ ${GUIDE} is missing the ${BEGIN} … ${END} markers`);
      process.exit(1);
    }
    if (next !== current) {
      writeFileSync(join(ROOT, GUIDE), next);
      console.log(`[write] ${GUIDE}`);
    }
    console.log(`[ok] ${summary()}`);
  }
}
