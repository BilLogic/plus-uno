#!/usr/bin/env node
//
// generate-check-scripts.mjs — the registry writes the three places that used
// to re-list the checks by hand.
//
// WHY THIS EXISTS
// ---------------
// `scripts/checks.registry.mjs` holds one row per check. Three other files
// stated the same set in their own words:
//
//   1. the `check:*` block of the root package.json — 46 lines binding a name
//      to a command, and the only place that binding exists;
//   2. `.github/workflows/harness-integrity-sweep.yml` — the monthly backstop,
//      which runs eight of them as spelled-out steps because `main` is
//      unprotected and a direct push never meets the PR gate;
//   3. `.github/workflows/storybook-gate.yml` — the browser job, which runs the
//      two checks the fast gate deliberately excludes.
//
// Nothing compared the four. A check could be registered and missing from a
// manifest, or run in a workflow while the registry said it ran nowhere, and
// both read as correct from inside each file. So the registry is now the author
// of the generated regions of all three, and `--check` fails on drift — the
// same shape as `scripts/generate-uno-skill-surfaces.mjs` and
// `check:skill-surfaces`.
//
// WHAT IT DOES NOT OWN. Everything outside the markers: every `generate:*`,
// `dev:*` and `build:*` script, and every workflow step that is not a check
// (the checkouts, the Node setup, the sibling clones, the Claude action). The
// markers are narrow on purpose — a generator that owns a whole file is a
// generator that eats the hand-written reasoning around it.
//
// `agents/uno-bot/package.json` is NOT generated: only six of its scripts are
// registered and the rest are commands. Its rows are COMPARED instead, which
// catches the same drift without taking authorship of a file this registry
// only half describes.
//
// AND EVERY TRIGGER IS ASSERTED, NOT JUST THE TWO THIS SCRIPT WRITES. The
// `trigger` column names four places a check runs, and generation reaches two
// of them. The other two — the pull-request workflows and the Worker's `deploy`
// chain — were honoured by hand: a row could claim `pull_request` and be run by
// nothing, or the chain could gain a step no row knew about, and each file read
// as correct alone. Both are now READ and compared in both directions, at the
// bottom of this file: a row with a trigger and no step fails, and a step with
// no row fails. Neither is generated, and the reasons are with
// `PULL_REQUEST_WORKFLOWS` and `DEPLOY_CHAIN` in the registry — briefly, the
// pull-request workflows are jobs wrapped in forty lines of measured argument,
// and the last segment of the deploy chain is the command that reaches a real
// Cloudflare account.
//
// Usage:
//   node scripts/generate-check-scripts.mjs           # write
//   node scripts/generate-check-scripts.mjs --check   # CI: fail on drift

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  ALL,
  CHECKS,
  COMPOSITE,
  DEPLOY_CHAIN,
  EXCLUDED,
  PULL_REQUEST_WORKFLOWS,
  WORKFLOW_STEPS,
  rootCheckRows,
  stepsIn,
  triggersOf,
  workflowRegions,
} from './checks.registry.mjs';
import { isEntry, report } from './lib/findings.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const REMEDY =
  '  The registry in scripts/checks.registry.mjs is the author of these blocks.\n' +
  '  Edit the row, then:\n' +
  '    npm run generate:check-registry\n' +
  "  The pull-request workflows and the Worker's deploy chain are COMPARED, not\n" +
  '  written: a finding about either is answered by editing the trigger, the\n' +
  '  DEPLOY_CHAIN entry or the step — regenerating will not move it.\n' +
  '  A check listed in one place and forgotten in another is the orphan this\n' +
  '  harness exists to prevent, one level up.';

const PKG = 'package.json';
const MARKER_BEGIN = (region) =>
  `      # >>> GENERATED (${region}) by scripts/generate-check-scripts.mjs from ` +
  `scripts/checks.registry.mjs — do not edit between the markers; run \`npm run generate:check-registry\`.`;
const MARKER_END = (region) => `      # <<< END GENERATED (${region})`;

const PKG_BEGIN = '//check-registry:begin';
const PKG_END = '//check-registry:end';
const PKG_BEGIN_NOTE =
  'GENERATED by scripts/generate-check-scripts.mjs from scripts/checks.registry.mjs — ' +
  'every check:* name below is a registry row. Add a check by adding a row, then run ' +
  '`npm run generate:check-registry`. `npm run check:check-registry` fails on drift.';
const PKG_END_NOTE = 'END of the generated check:* block.';

// ---------------------------------------------------------------------------
// package.json
// ---------------------------------------------------------------------------

/** The `"scripts": { … }` object as raw lines, so untouched lines stay byte-identical. */
function scriptLines(text) {
  const lines = text.split('\n');
  const open = lines.findIndex((l) => /^ {2}"scripts": \{$/.test(l));
  if (open < 0) throw new Error('package.json: no "scripts" object to read');
  const close = lines.findIndex((l, i) => i > open && /^ {2}\},?$/.test(l));
  if (close < 0) throw new Error('package.json: the "scripts" object never closes');
  return { lines, open, close, inside: lines.slice(open + 1, close) };
}

const keyOf = (line) => /^\s*"((?:[^"\\]|\\.)*)":/.exec(line)?.[1] ?? null;
const generatedKey = (key) =>
  key !== null && (key.startsWith('check:') || key === PKG_BEGIN || key === PKG_END);

const scriptLine = (name, command) =>
  `    ${JSON.stringify(name)}: ${JSON.stringify(command)}`;

/**
 * The root package.json with its generated `check:*` block rewritten.
 *
 * The block sits at the END of the scripts object rather than where the 46
 * names used to be scattered: they were interleaved with the `generate:*` they
 * pair with, and no contiguous region could hold them without moving something.
 * Object key order means nothing to npm, and one block that a generator owns is
 * worth more than an adjacency a reader has to trust.
 */
export function renderPackageJson(text) {
  const { lines, open, close, inside } = scriptLines(text);
  const kept = inside.filter((line) => !generatedKey(keyOf(line)));
  const block = [
    scriptLine(PKG_BEGIN, PKG_BEGIN_NOTE),
    ...rootCheckRows().map((row) => scriptLine(row.name, row.script)),
    scriptLine(PKG_END, PKG_END_NOTE),
  ];
  const body = [...kept.map((l) => l.replace(/,\s*$/, '')), ...block];
  return [...lines.slice(0, open + 1), body.join(',\n'), ...lines.slice(close)].join('\n');
}

// ---------------------------------------------------------------------------
// workflows
// ---------------------------------------------------------------------------

/** One step of a workflow, rendered from its registry row. */
function renderStep(step) {
  const out = [];
  for (const line of step.note ?? []) out.push(line ? `      # ${line}` : '      #');
  out.push(`      - name: ${step.name}`);
  if (step.env) {
    out.push('        env:');
    for (const [key, value] of Object.entries(step.env)) out.push(`          ${key}: ${value}`);
  }
  if (step.runs.length === 1) out.push(`        run: npm run ${step.runs[0]}`);
  else {
    out.push('        run: |');
    for (const name of step.runs) out.push(`          npm run ${name}`);
  }
  return out.join('\n');
}

export const renderRegion = (workflow, region) =>
  stepsIn(workflow, region).map(renderStep).join('\n\n');

/**
 * Replace every marked region of one workflow. Markers are never written by
 * this script: a region the file does not declare is a question for a human,
 * because only the surrounding YAML says where the steps belong.
 */
export function renderWorkflow(workflow, text, regions) {
  let out = text;
  for (const region of regions) {
    const begin = MARKER_BEGIN(region);
    const end = MARKER_END(region);
    const from = out.indexOf(begin);
    const to = out.indexOf(end);
    if (from < 0 || to < 0 || to < from) {
      throw new Error(
        `${workflow}: no marker pair for region '${region}'. Add these two lines around the ` +
          `steps the registry should own:\n${begin}\n${end}`,
      );
    }
    out =
      out.slice(0, from + begin.length) +
      `\n${renderRegion(workflow, region)}\n` +
      out.slice(to);
  }
  return out;
}

// ---------------------------------------------------------------------------
// the artifacts, and the comparisons that are not generation
// ---------------------------------------------------------------------------

const read = (file) => fs.readFileSync(path.join(REPO_ROOT, file), 'utf8');

/** @returns {{file: string, content: string}[]} */
export function artifacts() {
  const out = [{ file: PKG, content: renderPackageJson(read(PKG)) }];
  for (const [workflow, regions] of workflowRegions()) {
    out.push({ file: workflow, content: renderWorkflow(workflow, read(workflow), regions) });
  }
  return out;
}

/** The npm script a file is bound to, per manifest, for the comparison below. */
const manifestScripts = (pkg) =>
  JSON.parse(read(pkg === 'bot' ? 'agents/uno-bot/package.json' : PKG)).scripts ?? {};

/**
 * Everything the registry claims that a generated block cannot state: that each
 * row's command is the one its manifest holds, that a declared baseline exists
 * and is read by the script that declares it, and that the workflow steps and
 * the `trigger` column agree in both directions.
 *
 * @returns {import('./lib/findings.mjs').Finding[]}
 */
export function consistencyFindings() {
  const found = [];
  const scripts = { root: manifestScripts('root'), bot: manifestScripts('bot') };

  for (const row of ALL) {
    const actual = scripts[row.pkg][row.name];
    const manifest = row.pkg === 'bot' ? 'agents/uno-bot/package.json' : PKG;
    if (actual === undefined) {
      found.push({
        file: manifest,
        message: `${row.name} is registered but ${manifest} has no such script.`,
      });
    } else if (actual !== row.script) {
      found.push({
        file: manifest,
        message:
          `${row.name} runs ${JSON.stringify(actual)} in ${manifest}, but the registry says ` +
          `${JSON.stringify(row.script)}.`,
      });
    }

    // Every row is a function or a process, and says which (#509). A row with
    // neither used to mean "spawn it", which made the registry's silence carry
    // a decision; the runner now refuses to guess, so this is where the reader
    // finds out.
    if (row.module && row.kind) {
      found.push({
        message: `${row.name} declares both a module and kind: '${row.kind}'. It is one or the other.`,
      });
    } else if (row.module) {
      if (!fs.existsSync(path.join(REPO_ROOT, row.module))) {
        found.push({ message: `${row.name} declares module ${row.module}, which does not exist.` });
      }
    } else if (row.kind !== 'spawn') {
      found.push({
        message:
          `${row.name} declares neither a \`module\` on the findings interface nor ` +
          "`kind: 'spawn'`. One of the two, and a spawn says why.",
      });
    } else if (!row.spawnReason) {
      found.push({
        message: `${row.name} is kind: 'spawn' with no spawnReason. Say why it cannot return findings.`,
      });
    }

    if (!row.baseline) continue;
    if (!fs.existsSync(path.join(REPO_ROOT, row.baseline))) {
      found.push({
        message: `${row.name} declares baseline ${row.baseline}, which does not exist.`,
      });
      continue;
    }
    const implementation = /(scripts\/[\w.-]+\.(?:mjs|js))/.exec(row.script)?.[1];
    if (implementation && fs.existsSync(path.join(REPO_ROOT, implementation))) {
      const source = read(implementation);
      if (!source.includes(path.basename(row.baseline))) {
        found.push({
          file: implementation,
          message:
            `${row.name} declares baseline ${row.baseline}, which ${implementation} never names. ` +
            'The registry is describing a ratchet the check does not read.',
        });
      }
    }
  }

  const registered = new Map(ALL.map((row) => [row.name, row]));
  const WORKFLOW_TRIGGER = {
    '.github/workflows/harness-integrity-sweep.yml': 'sweep',
    '.github/workflows/storybook-gate.yml': 'storybook-gate',
  };

  for (const step of WORKFLOW_STEPS) {
    const trigger = WORKFLOW_TRIGGER[step.workflow];
    for (const name of step.runs) {
      const row = registered.get(name);
      if (!row) {
        found.push({
          file: step.workflow,
          message: `step '${step.name}' runs ${name}, which is not a registry row.`,
        });
      } else if (trigger && !triggersOf(row).includes(trigger)) {
        found.push({
          message:
            `${name} is a step of ${step.workflow} but its trigger is ` +
            `[${triggersOf(row).join(', ')}] — add '${trigger}'.`,
        });
      }
    }
  }

  for (const [workflow, trigger] of Object.entries(WORKFLOW_TRIGGER)) {
    const inWorkflow = new Set(
      WORKFLOW_STEPS.filter((s) => s.workflow === workflow).flatMap((s) => s.runs),
    );
    for (const row of ALL) {
      if (triggersOf(row).includes(trigger) && !inWorkflow.has(row.name)) {
        found.push({
          file: workflow,
          message:
            `${row.name} declares trigger '${trigger}' but no step of ${workflow} runs it. ` +
            'Add a WORKFLOW_STEPS entry, or correct the trigger.',
        });
      }
    }
  }

  // The other two triggers. All four are asserted now, which is the whole of
  // the registry's `trigger` column no longer has a column nobody reads.
  found.push(...pullRequestFindings(pullRequestRuns()));
  found.push(...deployChainFindings());

  return found;
}

// ---------------------------------------------------------------------------
// the two triggers that are honoured by hand-written files
//
// `sweep` and `storybook-gate` are asserted above, against WORKFLOW_STEPS,
// because the registry writes those steps. The other two are not written from
// here — the pull-request workflows are jobs with installs and forty lines of
// measured argument around each `run:`, and the deploy chain ends in the
// command that reaches a real Cloudflare account. Both are therefore READ and
// compared, in both directions, which is the same guarantee without the
// generator taking the pen.
// ---------------------------------------------------------------------------

/**
 * The npm script names a workflow's steps run, in file order.
 *
 * Read with a line regex rather than a YAML parse, on the rule every member of
 * this gate keeps: it runs on a clean checkout with no install
 * (`scripts/check-harness.mjs`), and the root manifest has no YAML dependency
 * to reach for. `scripts/node-floor.mjs` reads `node-version:` the same way.
 *
 * Installs are not gates, so `npm ci` and `npm install` are skipped; anything
 * that is not an npm invocation (a checkout, a shell script, an action) is not
 * a named script and cannot be a registry row either.
 *
 * @param {string} text  the workflow file.
 * @returns {string[]}
 */
export function runsIn(text) {
  const names = [];
  const lines = text.split('\n');
  const take = (command) => {
    const trimmed = command.trim();
    if (/^npm\s+(ci|install)\b/.test(trimmed)) return;
    const run = /^npm\s+run\s+(?:--silent\s+)?([\w:.@/-]+)/.exec(trimmed);
    if (run) {
      names.push(run[1]);
      return;
    }
    const bare = /^npm\s+(test|start)\s*$/.exec(trimmed);
    if (bare) names.push(bare[1]);
  };

  for (let i = 0; i < lines.length; i += 1) {
    const block = /^(\s*)run:\s*[|>][-+]?\s*$/.exec(lines[i]);
    if (block) {
      const outer = block[1].length;
      for (let j = i + 1; j < lines.length; j += 1) {
        if (lines[j].trim() === '') continue;
        if (lines[j].search(/\S/) <= outer) break;
        take(lines[j]);
        i = j;
      }
      continue;
    }
    const inline = /^\s*run:\s*(\S.*)$/.exec(lines[i]);
    if (inline) take(inline[1]);
  }
  return names;
}

/** Each pull-request workflow with the script names its steps run. */
export const pullRequestRuns = () =>
  new Map(PULL_REQUEST_WORKFLOWS.map((file) => [file, runsIn(read(file))]));

/**
 * The `pull_request` trigger against the steps that honour it, both ways.
 *
 * A row reaches a pull request by one of three routes, and the registry states
 * all three: a step names it; it is composed into `COMPOSITE`, which a step
 * names; or it declares `stepOf`, naming the composed row that spawns it. A
 * row with the trigger and none of the three is the orphan this file exists to
 * report — `test:workerd` was one for three months, gated as a hand-written
 * step while the registry said it ran nowhere (#587).
 *
 * @param {Map<string, string[]>} workflowRuns
 * @returns {import('./lib/findings.mjs').Finding[]}
 */
export function pullRequestFindings(workflowRuns, { rows = ALL, composed = CHECKS } = {}) {
  const found = [];
  const byRowName = new Map(rows.map((row) => [row.name, row]));
  const composedNames = new Set(composed.map((row) => row.name));
  const named = new Map();

  for (const [file, names] of workflowRuns) {
    for (const name of names) {
      named.set(name, file);
      const row = byRowName.get(name);
      if (!row) {
        found.push({
          file,
          message: `a step runs \`npm run ${name}\`, which is not a registry row. Add one, or stop running it.`,
        });
      } else if (!triggersOf(row).includes('pull_request')) {
        found.push({
          file,
          message:
            `${name} is run by ${file}, a pull-request workflow, but its trigger is ` +
            `[${triggersOf(row).join(', ')}] — add 'pull_request'.`,
        });
      }
    }
  }

  const reaches = (row, seen = new Set()) => {
    if (seen.has(row.name)) return false;
    seen.add(row.name);
    if (named.has(row.name)) return true;
    if (composedNames.has(row.name) && named.has(COMPOSITE)) return true;
    const parent = row.stepOf && byRowName.get(row.stepOf);
    return parent ? reaches(parent, seen) : false;
  };

  const files = [...workflowRuns.keys()].join(' or ');
  for (const row of rows) {
    if (row.stepOf) {
      if (!byRowName.has(row.stepOf)) {
        found.push({
          message: `${row.name} declares stepOf '${row.stepOf}', which is not a registry row.`,
        });
      } else if (row.reason && !row.reason.includes(row.stepOf)) {
        found.push({
          message:
            `${row.name} declares stepOf '${row.stepOf}', which its \`reason\` never names. ` +
            'The column and the prose are the same claim; say it the same way.',
        });
      }
    }
    if (!triggersOf(row).includes('pull_request') || reaches(row)) continue;
    found.push({
      message:
        `${row.name} declares trigger 'pull_request' but no step of ${files} runs it, it is ` +
        `not composed into ${COMPOSITE}, and it names no \`stepOf\`. Add a step, compose it, ` +
        'or correct the trigger.',
    });
  }

  return found;
}

/** The `deploy` script of the Worker's manifest, as its `&&`-separated segments. */
export const deployChain = () =>
  (manifestScripts('bot').deploy ?? '')
    .split('&&')
    .map((segment) => segment.trim())
    .filter(Boolean);

/**
 * The `deploy` trigger against the chain that honours it, both ways.
 *
 * @param {string} [script]  the `deploy` script; the manifest's, by default.
 * @returns {import('./lib/findings.mjs').Finding[]}
 */
export function deployChainFindings(script, { rows = ALL, chain = DEPLOY_CHAIN } = {}) {
  const found = [];
  const manifest = 'agents/uno-bot/package.json';
  const actual =
    script === undefined
      ? deployChain()
      : script
          .split('&&')
          .map((segment) => segment.trim())
          .filter(Boolean);
  const expected = chain.map((entry) => entry.step);

  if (actual.join(' && ') !== expected.join(' && ')) {
    found.push({
      file: manifest,
      message:
        'the deploy chain and the registry disagree.\n' +
        `           manifest: ${actual.join(' && ')}\n` +
        `           registry: ${expected.join(' && ')}`,
    });
  }

  const byRowName = new Map(rows.map((row) => [row.name, row]));
  const gates = new Set();
  for (const entry of chain) {
    if (entry.runs && entry.notAGate) {
      found.push({
        message: `the deploy chain's '${entry.step}' is both a gate and not one. It is one or the other.`,
      });
      continue;
    }
    if (!entry.runs) {
      if (!entry.notAGate) {
        found.push({
          message:
            `the deploy chain's '${entry.step}' runs no registry row and says nothing about ` +
            'why. Give it a `runs`, or a `notAGate` saying what it is.',
        });
      }
      continue;
    }
    gates.add(entry.runs);
    const invocations = [`npm run ${entry.runs}`, `npm ${entry.runs}`];
    if (!invocations.includes(entry.step)) {
      found.push({
        message: `the deploy chain's '${entry.step}' claims to run ${entry.runs}. It does not.`,
      });
    }
    const row = byRowName.get(entry.runs);
    if (!row) {
      found.push({
        message: `the deploy chain runs ${entry.runs}, which is not a registry row.`,
      });
    } else if (!triggersOf(row).includes('deploy')) {
      found.push({
        message:
          `${entry.runs} is a gate of the deploy chain but its trigger is ` +
          `[${triggersOf(row).join(', ')}] — add 'deploy'.`,
      });
    }
  }

  for (const row of rows) {
    if (!triggersOf(row).includes('deploy') || gates.has(row.name)) continue;
    found.push({
      file: manifest,
      message:
        `${row.name} declares trigger 'deploy' but no step of the chain runs it. Add a ` +
        'DEPLOY_CHAIN entry, or correct the trigger.',
    });
  }

  return found;
}

/**
 * The drift check. `run(ctx)` is the findings interface
 * (`scripts/lib/findings.mjs`): this check reports and never writes, which is
 * the rule `--check` exists for — a check that regenerates its own target
 * answers "is the committed file stale?" with the bytes it just wrote.
 *
 * @returns {import('./lib/findings.mjs').Finding[]}
 */
export function run() {
  const found = [];
  let rendered;
  try {
    rendered = artifacts();
  } catch (error) {
    return [{ message: error.message }];
  }
  for (const { file, content } of rendered) {
    if (read(file) !== content) {
      found.push({ file, message: 'is stale against the registry.' });
    }
  }
  return [...found, ...consistencyFindings()];
}

export const summary = () =>
  `${CHECKS.length} registered + ${EXCLUDED.length} excluded checks, ` +
  `${rootCheckRows().length} in package.json, ${WORKFLOW_STEPS.length} workflow steps, ` +
  `${PULL_REQUEST_WORKFLOWS.length} pull-request workflows, ` +
  `${DEPLOY_CHAIN.length}-step deploy chain — all four triggers asserted, no drift`;

// `main()` is not the shape here: its default branch is the gate, and this
// file's default is the WRITE — `--check` is the side door. So the entry
// comparison is asked of `isEntry` and the two branches stay here (#610).
if (isEntry(import.meta.url)) {
  if (process.argv.includes('--check')) {
    report('check:check-registry', run(), { remedy: REMEDY, summary: summary() });
  } else {
    const written = [];
    for (const { file, content } of artifacts()) {
      if (read(file) === content) continue;
      fs.writeFileSync(path.join(REPO_ROOT, file), content);
      written.push(file);
      console.log(`[write] ${file}`);
    }
    if (!written.length) console.log('[ok] every generated block already matches the registry');
    const found = consistencyFindings();
    if (found.length) report('check:check-registry', found, { remedy: REMEDY });
    console.log(`[ok] ${summary()}`);
  }
}
