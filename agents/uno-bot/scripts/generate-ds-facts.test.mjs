import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import {
  DS_FACTS_BYTE_BUDGET,
  DS_FACTS_PATH,
  artifacts,
  bakeFacts,
  budgetOverrun,
  generatedDocFor,
  renderDsFacts,
  run,
} from "./generate-ds-facts.mjs";

function writeFixtureFacts(root, components) {
  const views = join(root, "design-system/agent-views");
  mkdirSync(views, { recursive: true });
  writeFileSync(join(views, "components.json"), JSON.stringify({ components }, null, 2), "utf8");
  writeFileSync(
    join(views, "tokens.json"),
    JSON.stringify({
      tokens: [{ name: "--stack-md", tier: "semantic", group: "Ladder Semantics", value: "var(--space-050)", intent: "Gap between items." }],
    }),
    "utf8",
  );
  writeFileSync(
    join(views, "_inventions.json"),
    JSON.stringify({ components: [{ not: "Tile", use: ["Card"], why: "a template" }], props: [], tokens: [] }),
    "utf8",
  );
}

/** The facts module's surface, as much of it as the bake reads. */
function fakeFacts() {
  const answers = {
    Button: { kind: "component", import: "import { Button } from '@/components';", group: "forms", source: "x/Button.jsx", summary: null, aliasOf: null, props: [{ name: "appearance", type: "enum", required: false, default: "primary", values: ["primary", "subtle"], description: "long words", deprecated: null }] },
    Card: { kind: "template", import: "import { Card } from '@/templates';", group: "Card", source: "p/Card.jsx", summary: "A raised container.", aliasOf: null, props: null },
  };
  return {
    manifests: {
      components: { components: [{ name: "Button" }, { name: "Card" }] },
      tokens: { tokens: [{ name: "--stack-md", tier: "semantic", group: "Ladder Semantics", value: "var(--space-050)", intent: "Gap between items." }] },
    },
    lookup: (name) => ({ name, status: "exists", ...answers[name] }),
    barrels: { "@/components": new Set(["Button", "BUTTON_SIZES"]), "@/templates": new Set(["Card"]) },
    retired: new Map([["--stack-xl", "--stack-lg"]]),
  };
}

const INVENTIONS = { components: [{ not: "Tile", use: ["Card"], why: "a template" }], props: [], tokens: [] };

describe("the baked DS facts", () => {
  it("keeps what the bot answers with and drops prop descriptions and empty fields", () => {
    const baked = bakeFacts(fakeFacts(), { docFor: (name) => (name === "Button" ? "design-system/src/components/forms/Button/index.md" : null), inventions: INVENTIONS });
    assert.deepEqual(baked.components, [
      {
        name: "Button",
        kind: "component",
        import: "import { Button } from '@/components';",
        group: "forms",
        source: "x/Button.jsx",
        doc: "design-system/src/components/forms/Button/index.md",
        props: [{ name: "appearance", type: "enum", values: ["primary", "subtle"], default: "primary" }],
      },
      { name: "Card", kind: "template", import: "import { Card } from '@/templates';", group: "Card", source: "p/Card.jsx", summary: "A raised container." },
    ]);
    assert.deepEqual(baked.barrels, { "@/components": ["BUTTON_SIZES", "Button"], "@/templates": ["Card"] });
    assert.deepEqual(baked.tokens, [["--stack-md", "semantic", 0, "var(--space-050)", "Gap between items."]]);
    assert.deepEqual(baked.tokenGroups, ["Ladder Semantics"]);
    assert.deepEqual(baked.inventions.components, [{ not: "Tile", use: ["Card"], why: "a template" }]);
    assert.deepEqual(baked.retired, [["--stack-xl", "--stack-lg"]]);
  });

  it("renders a typed module the Worker imports", () => {
    const text = renderDsFacts(bakeFacts(fakeFacts(), { inventions: INVENTIONS }));
    assert.match(text, /^\/\/ GENERATED by scripts\/generate-ds-facts\.mjs/);
    assert.match(text, /export const DS_FACTS: BakedDsFacts = \{/);
  });

  it("finds a component's generated doc in its own folder or filed flat, and none for a name without one", () => {
    const root = mkdtempSync(join(tmpdir(), "ds-facts-"));
    mkdirSync(join(root, "design-system/src/components/forms/Button"), { recursive: true });
    writeFileSync(join(root, "design-system/src/components/forms/Button/index.md"), "#");
    writeFileSync(join(root, "design-system/src/components/forms/TreeSelect.md"), "#");
    assert.equal(generatedDocFor(root, "Button"), "design-system/src/components/forms/Button/index.md");
    assert.equal(generatedDocFor(root, "TreeSelect"), "design-system/src/components/forms/TreeSelect.md");
    assert.equal(generatedDocFor(root, "Logo"), null);
  });

  it("holds the facts built into the Worker under their byte budget", () => {
    const committed = readFileSync(new URL("../src/generated/ds-facts.ts", import.meta.url), "utf8");
    const literal = committed.slice(committed.indexOf("= {") + 2, committed.lastIndexOf("};") + 1);
    assert.equal(budgetOverrun(JSON.stringify(JSON.parse(literal))), null);
  });

  it("measures the payload, so line breaks in the source file do not count", () => {
    const baked = { components: Array.from({ length: 50 }, (_, i) => ({ name: `C${i}` })) };
    const payload = JSON.stringify(baked);
    const laidOut = renderDsFacts(baked);
    assert.ok(Buffer.byteLength(laidOut) > Buffer.byteLength(payload) + 50);
    assert.equal(budgetOverrun(payload, Buffer.byteLength(payload)), null);
    assert.match(budgetOverrun(laidOut, Buffer.byteLength(payload)) ?? "", /over DS_FACTS_BYTE_BUDGET/);
  });

  it("names the overrun in bytes, counting multi-byte characters as bytes", () => {
    assert.equal(budgetOverrun("x".repeat(DS_FACTS_BYTE_BUDGET)), null);
    assert.match(budgetOverrun("x".repeat(DS_FACTS_BYTE_BUDGET + 1)), /1 byte over/);
    assert.match(budgetOverrun("x".repeat(DS_FACTS_BYTE_BUDGET - 3) + "——"), /3 bytes over/);
  });

  it("holds the committed DS facts module in sync with the root facts module", () => {
    assert.deepEqual(run(), []);
  });

  it("detects missing output, edited output, and stale source without writing in verification mode, and regenerates deterministically", () => {
    const root = mkdtempSync(join(tmpdir(), "ds-facts-check-"));
    try {
      writeFixtureFacts(root, [
        {
          name: "Button",
          kind: "component",
          import: "import { Button } from '@/components';",
          group: "forms",
          source: "design-system/src/components/forms/Button/Button.jsx",
          props: [{ name: "appearance", type: "enum", values: ["primary", "subtle"], default: "primary" }],
        },
      ]);
      const outAbs = join(root, DS_FACTS_PATH);

      assert.deepEqual(
        run({ repoRoot: root }).map((f) => f.file),
        [DS_FACTS_PATH],
      );
      assert.equal(existsSync(outAbs), false, "check mode must not create a missing output file");

      const [first] = artifacts(root);
      const [second] = artifacts(root);
      assert.equal(first.path, DS_FACTS_PATH);
      assert.equal(first.content, second.content, "regeneration must be deterministic");

      mkdirSync(dirname(outAbs), { recursive: true });
      writeFileSync(outAbs, first.content, "utf8");
      assert.deepEqual(run({ repoRoot: root }), []);
      assert.match(run({ repoRoot: root, budget: 10 })[0]?.message ?? "", /over DS_FACTS_BYTE_BUDGET/);

      const edited = `${first.content}// hand-edited\n`;
      writeFileSync(outAbs, edited, "utf8");
      assert.deepEqual(
        run({ repoRoot: root }).map((f) => f.file),
        [DS_FACTS_PATH],
      );
      assert.equal(readFileSync(outAbs, "utf8"), edited, "check mode must not overwrite an edited output file");

      writeFileSync(outAbs, first.content, "utf8");
      writeFixtureFacts(root, [
        {
          name: "Button",
          kind: "component",
          import: "import { Button } from '@/components';",
          group: "forms",
          source: "design-system/src/components/forms/Button/Button.jsx",
          props: [{ name: "appearance", type: "enum", values: ["primary", "subtle", "danger"], default: "primary" }],
        },
      ]);
      assert.deepEqual(
        run({ repoRoot: root }).map((f) => f.file),
        [DS_FACTS_PATH],
      );
      assert.equal(readFileSync(outAbs, "utf8"), first.content, "check mode must not write when source moves ahead");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
