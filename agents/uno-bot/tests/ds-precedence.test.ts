function kv<T>(initial: T) {
  const box = { value: initial, writes: 0 };
  return {
    box,
    store: {
      read: async () => box.value,
      write: async (v: T) => {
        box.value = v;
        box.writes += 1;
      },
    },
  };
}

function checkDeps(library: FigmaComponentsResponse, report = kv<PrecedenceReport | null>(null)) {
  const deps: CheckDeps = {
    github: { indexMarkdown: async () => INDEX_MD, registry: async () => REGISTRY },
    figma: { components: async () => library },
    report: report.store,
    inFlight: async () => new Set<string>(),
    fileKey: FILE_KEY,
    repo: REPO,
    now: () => Date.UTC(2026, 9, 2, 22, 0),
  };
  return { deps, report };
}

