/**
 * The one agent text for a component or pattern: what
 * `generate:component-docs` writes as its generated doc and what the DS
 * lookup's `get` returns, byte for byte.
 *
 *   renderComponent(facts, docs)   the text
 *     facts  one record of the components manifest (`agent-manifests.mjs`),
 *            with `related` and `aliases`: `componentFacts` builds it
 *     docs   `{path, page}`: the component's docs page and its page model
 *            (`docs-page.mjs`), or null when it has none
 *   componentFacts(manifest, name, aliasRows?)  the record plus its same-group siblings and aliases
 *   docPathOf(record)              where the generated doc is written
 *   SECTION_TITLES                 the `##` sections of the text each `get` section is
 *
 * Pure: nothing here reads the disk. The generator hands it the manifest it is
 * building in the same run, never the one the last run wrote; the lookup hands
 * it the committed manifest, which `check:component-docs` holds equal to a
 * fresh run.
 *
 * WHAT IT CARRIES. The facts derived from source (summary, import, stories,
 * props, variants, sub-components, tokens touched, the Figma set and node),
 * then the authored spine read from the page: Usage, Content guidelines,
 * Alternatives, Best practices as one `###` rule each with its id,
 * Accessibility, and Related. No raw Figma URL and no hint about which tool
 * to call next: an adapter that wants a hint adds it.
 */

import path from 'node:path';

import { AUTHORED_SECTIONS, coverageOf } from './authored-coverage.mjs';
import { sectionText } from './docs-page.mjs';

export const GENERATED_HEADER = '<!-- DO NOT EDIT BY HAND. Generated by npm run generate:component-docs -->';

/** The `##` sections of the text behind each `get` section. */
export const SECTION_TITLES = {
  props: ['Props', 'Variants', 'Sub-components'],
  usage: ['Usage', 'Content guidelines', 'Alternatives'],
  examples: ['Best practices'],
  a11y: ['Accessibility'],
  figma: ['Figma'],
};

/**
 * A manifest record with `related`, the other records of its kind filed in its
 * group, and `aliases`, the words it is asked by (`agent-views/_aliases.json`'s
 * `components`, passed in).
 */
export function componentFacts(manifest, name, aliasRows = {}) {
  const records = manifest.components ?? manifest;
  const record = records.find((r) => r.name === name);
  if (!record) return null;
  const related = records
    .filter((r) => r.name !== name && r.source && r.kind === record.kind && r.group === record.group)
    .map((r) => r.name)
    .sort();
  return { ...record, related, aliases: [...(aliasRows[name] ?? [])] };
}

/** `<dir>/index.md` for a component in a folder of its own name, `<dir>/<Name>.md` for one filed flat. */
export function docPathOf({ name, source }) {
  const dir = path.posix.dirname(source);
  return path.posix.basename(dir) === path.posix.basename(source).replace(/\.[jt]sx?$/, '')
    ? `${dir}/index.md`
    : `${dir}/${name}.md`;
}

const code = (s) => `\`${s}\``;
/** The file beside a component's source with another extension: its stories, its stylesheet. */
const sibling = (source, ext) => source.replace(/\.[jt]sx?$/, ext);

function propsTable(rows) {
  let d = `| Prop | Type | Default | Description |\n|------|------|---------|-------------|\n`;
  for (const p of rows) d += `| ${code(p.name)} | ${p.type}${p.required ? ' (required)' : ''} | ${p.default ? code(p.default) : '—'} | ${p.description || '—'} |\n`;
  return `${d}\n`;
}

/** The authored spine, from the page model. */
function spine(page) {
  if (!page) return '';
  let d = '';
  const section = (title) => {
    const text = sectionText(page, title);
    if (text) d += `## ${title}\n\n${text}\n\n`;
  };
  section('Usage');
  section('Content guidelines');
  if (page.alternatives.length) d += `## Alternatives\n\n${page.alternatives.map((a) => `- ${a.text}`).join('\n')}\n\n`;
  if (page.rules.length) {
    d += `## Best practices\n\n`;
    for (const r of page.rules) d += `### ${r.sentence} {#${r.id}}\n\n${r.text ? `${r.text}\n\n` : ''}`;
  } else section('Best practices');
  section('Accessibility');
  return d;
}

/** The text (see the header). */
export function renderComponent(facts, docs) {
  const page = docs?.page ?? null;
  let d = `${GENERATED_HEADER}\n\n# ${facts.name}\n\n`;
  if (facts.summary) d += `${facts.summary}\n\n`;
  if (facts.aliases?.length) d += `Also asked as: ${facts.aliases.join(', ')}.\n\n`;
  if (facts.implementedAs) {
    d += `> Implemented as ${code(facts.implementedAs)} in the source and exported as ${code(facts.name)}. `;
    d += `Import the exported name; read the source under the implementation name.\n\n`;
  }
  d += facts.import ? `**Import:** ${code(facts.import)}\n\n` : `**Import:** none; it is not exported from a barrel.\n\n`;
  d += `**Source:** ${code(facts.source)}\n\n`;
  if (facts.stories) d += `**Stories:** ${code(sibling(facts.source, '.stories.jsx'))} — ${facts.stories.join(', ') || 'none exported'}\n\n`;
  if (docs?.path) d += `**Storybook page:** ${code(docs.path)}\n\n`;

  d += spine(page);

  const props = facts.props ?? [];
  if (props.length) d += `## Props\n\n${propsTable(props)}`;
  const enums = props.filter((p) => p.values?.length);
  if (enums.length) {
    d += `## Variants\n\n`;
    for (const e of enums) d += `**${code(e.name)}** — ${e.values.map(code).join(' · ')}\n\n`;
    d += `Anything not listed is not a valid value.\n\n`;
  }
  if (facts.subComponents?.length) {
    d += `## Sub-components\n\n`;
    for (const sub of facts.subComponents) {
      d += `### ${code(`${facts.name}.${sub.name}`)}\n\nImplemented as ${code(sub.impl)}.\n\n`;
      if (sub.props.length) d += propsTable(sub.props);
    }
  }
  if (facts.tokens?.length) {
    d += `## Tokens touched\n\n${facts.tokens.map(code).join(' · ')}\n\n`;
    d += `From ${code(sibling(facts.source, '.scss'))}. Override these through the token layer, never with a literal.\n\n`;
  }
  const sets = page?.figmaMeta?.sets ?? [];
  if (sets.length) {
    d += `## Figma\n\n`;
    for (const s of sets) {
      const node = s.componentSetNodeId ?? s.nodeId;
      d += `- "${s.name}"${node ? ` node ${node}` : ''}${page.figmaMeta.fileKey ? ` in file ${page.figmaMeta.fileKey}` : ''}\n`;
    }
    d += `\n`;
  }
  const related = page?.related ?? [];
  if (related.length || facts.related?.length) {
    d += `## Related\n\n`;
    if (related.length) d += `${related.map((r) => `- ${r}`).join('\n')}\n\n`;
    if (facts.related?.length) d += `Same group: ${facts.related.map(code).join(' · ')}\n\n`;
  }

  const coverage = coverageOf(page);
  const missing = AUTHORED_SECTIONS.filter((s) => !coverage[s.key]);
  d += `<!-- authored coverage: ${AUTHORED_SECTIONS.map((s) => `${s.key}=${coverage[s.key] ? 'yes' : 'no'}`).join(' ')} -->\n`;
  if (missing.length === AUTHORED_SECTIONS.length) {
    d += `\n> No authored guidance yet: when to use, correct/incorrect, and accessibility\n`;
    d += `> are unwritten for this component. Nothing above tells you whether\n`;
    d += `> reaching for ${code(facts.name)} is the right call, only what it accepts.\n`;
  } else if (missing.length) {
    d += `\n> Authored guidance is partial: missing ${missing.map((m) => m.label.toLowerCase()).join(', ')}.\n`;
  }
  return d;
}

/** The `##` sections of a rendered text named in `titles`, in the text's order, joined; null when it has none. */
export function sectionsOf(text, titles) {
  const blocks = text.split(/\n(?=## )/).filter((b) => titles.includes(b.match(/^## (.*)/)?.[1]));
  return blocks.length ? blocks.map((b) => b.replace(/\n<!-- authored coverage[\s\S]*$/, '').trim()).join('\n\n') : null;
}
