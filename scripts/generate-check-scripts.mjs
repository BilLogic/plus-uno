#!/usr/bin/env node
//
// generate-check-scripts.mjs — the registry writes the three places that used
// to re-list the checks by hand.
//
// WHY THIS EXISTS
// ---------------
// `scripts/checks.registry.mjs` holds one row per check. Three other files
// stated the same set in their own words:
//
//   1. the `check:*` block of the root package.json — 46 lines binding a name
//      to a command, and the only place that binding exists;
//   2. `.github/workflows/harness-integrity-sweep.yml` — the monthly backstop,
//      which runs eight of them as spelled-out steps because `main` is
//      unprotected and a direct push never meets the PR gate;
//   3. `.github/workflows/storybook-gate.yml` — the browser job, which runs the
//      two checks the fast gate deliberately excludes.
//
// Nothing compared the four. A check could be registered and missing from a
// manifest, or run in a workflow while the registry said it ran nowhere, and
// both read as correct from inside each file. So the registry is now the author
// of the generated regions of all three, and `--check` fails on drift — the
// same shape as `scripts/generate-uno-skill-surfaces.mjs` and
// `check:skill-surfaces`.
//
// WHAT IT DOES NOT OWN. Everything outside the markers: every `generate:*`,
// `dev:*` and `build:*` script, and every workflow step that is not a check
// (the checkouts, the Node setup, the sibling clones, the Claude action). The
// markers are narrow on purpose — a generator that owns a whole file is a
// generator that eats the hand-written reasoning around it.
//
// `agents/uno-bot/package.json` is NOT generated: only six of its scripts are
// registered and the rest are commands. Its rows are COMPARED instead, which
// catches the same drift without taking authorship of a file this registry
// only half describes.
//
// Usage:
//   node scripts/generate-check-scripts.mjs           # write
//   node scripts/generate-check-scripts.mjs --check   # CI: fail on drift

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
  ALL,
  CHECKS,
  EXCLUDED,
  WORKFLOW_STEPS,
  rootCheckRows,
  stepsIn,
  triggersOf,
  workflowRegions,
} from './checks.registry.mjs';
import { report } from './lib/findings.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const REMEDY =
  '  The registry in scripts/checks.registry.mjs is the author of these blocks.\n' +
  '  Edit the row, then:\n' +
  '    npm run generate:check-registry\n' +
  '  A check listed in one place and forgotten in another is the orphan this\n' +
  '  harness exists to prevent, one level up.';

const PKG = 'package.json';
const MARKER_BEGIN = (region) =>
  `      # >>> GENERATED (${region}) by scripts/generate-check-scripts.mjs from ` +
  `scripts/checks.registry.mjs — do not edit between the markers; run \`npm run generate:check-registry\`.`;
const MARKER_END = (region) => `      # <<< END GENERATED (${region})`;

const PKG_BEGIN = '//check-registry:begin';
const PKG_END = '//check-registry:end';
const PKG_BEGIN_NOTE =
  'GENERATED by scripts/generate-check-scripts.mjs from scripts/checks.registry.mjs — ' +
  'every check:* name below is a registry row. Add a check by adding a row, then run ' +
  '`npm run generate:check-registry`. `npm run check:check-registry` fails on drift.';
const PKG_END_NOTE = 'END of the generated check:* block.';

// ---------------------------------------------------------------------------
// package.json
// ---------------------------------------------------------------------------

/** The `"scripts": { … }` object as raw lines, so untouched lines stay byte-identical. */
function scriptLines(text) {
  const lines = text.split('\n');
  const open = lines.findIndex((l) => /^ {2}"scripts": \{$/.test(l));
  if (open < 0) throw new Error('package.json: no "scripts" object to read');
  const close = lines.findIndex((l, i) => i > open && /^ {2}\},?$/.test(l));
  if (close < 0) throw new Error('package.json: the "scripts" object never closes');
  return { lines, open, close, inside: lines.slice(open + 1, close) };
}

const keyOf = (line) => /^\s*"((?:[^"\\]|\\.)*)":/.exec(line)?.[1] ?? null;
const generatedKey = (key) =>
  key !== null && (key.startsWith('check:') || key === PKG_BEGIN || key === PKG_END);

const scriptLine = (name, command) =>
  `    ${JSON.stringify(name)}: ${JSON.stringify(command)}`;

/**
 * The root package.json with its generated `check:*` block rewritten.
 *
 * The block sits at the END of the scripts object rather than where the 46
 * names used to be scattered: they were interleaved with the `generate:*` they
 * pair with, and no contiguous region could hold them without moving something.
 * Object key order means nothing to npm, and one block that a generator owns is
 * worth more than an adjacency a reader has to trust.
 */
export function renderPackageJson(text) {
  const { lines, open, close, inside } = scriptLines(text);
  const kept = inside.filter((line) => !generatedKey(keyOf(line)));
  const block = [
    scriptLine(PKG_BEGIN, PKG_BEGIN_NOTE),
    ...rootCheckRows().map((row) => scriptLine(row.name, row.script)),
    scriptLine(PKG_END, PKG_END_NOTE),
  ];
  const body = [...kept.map((l) => l.replace(/,\s*$/, '')), ...block];
  return [...lines.slice(0, open + 1), body.join(',\n'), ...lines.slice(close)].join('\n');
}

// ---------------------------------------------------------------------------
// workflows
// ---------------------------------------------------------------------------

/** One step of a workflow, rendered from its registry row. */
function renderStep(step) {
  const out = [];
  for (const line of step.note ?? []) out.push(line ? `      # ${line}` : '      #');
  out.push(`      - name: ${step.name}`);
  if (step.env) {
    out.push('        env:');
    for (const [key, value] of Object.entries(step.env)) out.push(`          ${key}: ${value}`);
  }
  if (step.runs.length === 1) out.push(`        run: npm run ${step.runs[0]}`);
  else {
    out.push('        run: |');
    for (const name of step.runs) out.push(`          npm run ${name}`);
  }
  return out.join('\n');
}

export const renderRegion = (workflow, region) =>
  stepsIn(workflow, region).map(renderStep).join('\n\n');

/**
 * Replace every marked region of one workflow. Markers are never written by
 * this script: a region the file does not declare is a question for a human,
 * because only the surrounding YAML says where the steps belong.
 */
export function renderWorkflow(workflow, text, regions) {
  let out = text;
  for (const region of regions) {
    const begin = MARKER_BEGIN(region);
    const end = MARKER_END(region);
    const from = out.indexOf(begin);
    const to = out.indexOf(end);
    if (from < 0 || to < 0 || to < from) {
      throw new Error(
        `${workflow}: no marker pair for region '${region}'. Add these two lines around the ` +
          `steps the registry should own:\n${begin}\n${end}`,
      );
    }
    out =
      out.slice(0, from + begin.length) +
      `\n${renderRegion(workflow, region)}\n` +
      out.slice(to);
  }
  return out;
}

// ---------------------------------------------------------------------------
// the artifacts, and the comparisons that are not generation
// ---------------------------------------------------------------------------

const read = (file) => fs.readFileSync(path.join(REPO_ROOT, file), 'utf8');

/** @returns {{file: string, content: string}[]} */
export function artifacts() {
  const out = [{ file: PKG, content: renderPackageJson(read(PKG)) }];
  for (const [workflow, regions] of workflowRegions()) {
    out.push({ file: workflow, content: renderWorkflow(workflow, read(workflow), regions) });
  }
  return out;
}

/** The npm script a file is bound to, per manifest, for the comparison below. */
const manifestScripts = (pkg) =>
  JSON.parse(read(pkg === 'bot' ? 'agents/uno-bot/package.json' : PKG)).scripts ?? {};

/**
 * Everything the registry claims that a generated block cannot state: that each
 * row's command is the one its manifest holds, that a declared baseline exists
 * and is read by the script that declares it, and that the workflow steps and
 * the `trigger` column agree in both directions.
 *
 * @returns {import('./lib/findings.mjs').Finding[]}
 */
export function consistencyFindings() {
  const found = [];
  const scripts = { root: manifestScripts('root'), bot: manifestScripts('bot') };

  for (const row of ALL) {
    const actual = scripts[row.pkg][row.name];
    const manifest = row.pkg === 'bot' ? 'agents/uno-bot/package.json' : PKG;
    if (actual === undefined) {
      found.push({
        file: manifest,
        message: `${row.name} is registered but ${manifest} has no such script.`,
      });
    } else if (actual !== row.script) {
      found.push({
        file: manifest,
        message:
          `${row.name} runs ${JSON.stringify(actual)} in ${manifest}, but the registry says ` +
          `${JSON.stringify(row.script)}.`,
      });
    }

    if (!row.baseline) continue;
    if (!fs.existsSync(path.join(REPO_ROOT, row.baseline))) {
      found.push({
        message: `${row.name} declares baseline ${row.baseline}, which does not exist.`,
      });
      continue;
    }
    const implementation = /(scripts\/[\w.-]+\.(?:mjs|js))/.exec(row.script)?.[1];
    if (implementation && fs.existsSync(path.join(REPO_ROOT, implementation))) {
      const source = read(implementation);
      if (!source.includes(path.basename(row.baseline))) {
        found.push({
          file: implementation,
          message:
            `${row.name} declares baseline ${row.baseline}, which ${implementation} never names. ` +
            'The registry is describing a ratchet the check does not read.',
        });
      }
    }
  }

  const registered = new Map(ALL.map((row) => [row.name, row]));
  const WORKFLOW_TRIGGER = {
    '.github/workflows/harness-integrity-sweep.yml': 'sweep',
    '.github/workflows/storybook-gate.yml': 'storybook-gate',
  };

  for (const step of WORKFLOW_STEPS) {
    const trigger = WORKFLOW_TRIGGER[step.workflow];
    for (const name of step.runs) {
      const row = registered.get(name);
      if (!row) {
        found.push({
          file: step.workflow,
          message: `step '${step.name}' runs ${name}, which is not a registry row.`,
        });
      } else if (trigger && !triggersOf(row).includes(trigger)) {
        found.push({
          message:
            `${name} is a step of ${step.workflow} but its trigger is ` +
            `[${triggersOf(row).join(', ')}] — add '${trigger}'.`,
        });
      }
    }
  }

  for (const [workflow, trigger] of Object.entries(WORKFLOW_TRIGGER)) {
    const inWorkflow = new Set(
      WORKFLOW_STEPS.filter((s) => s.workflow === workflow).flatMap((s) => s.runs),
    );
    for (const row of ALL) {
      if (triggersOf(row).includes(trigger) && !inWorkflow.has(row.name)) {
        found.push({
          file: workflow,
          message:
            `${row.name} declares trigger '${trigger}' but no step of ${workflow} runs it. ` +
            'Add a WORKFLOW_STEPS entry, or correct the trigger.',
        });
      }
    }
  }

  return found;
}

/**
 * The drift check. `run(ctx)` is the findings interface
 * (`scripts/lib/findings.mjs`): this check reports and never writes, which is
 * the rule `--check` exists for — a check that regenerates its own target
 * answers "is the committed file stale?" with the bytes it just wrote.
 *
 * @returns {import('./lib/findings.mjs').Finding[]}
 */
export function run() {
  const found = [];
  let rendered;
  try {
    rendered = artifacts();
  } catch (error) {
    return [{ message: error.message }];
  }
  for (const { file, content } of rendered) {
    if (read(file) !== content) {
      found.push({ file, message: 'is stale against the registry.' });
    }
  }
  return [...found, ...consistencyFindings()];
}

export const summary = () =>
  `${CHECKS.length} registered + ${EXCLUDED.length} excluded checks, ` +
  `${rootCheckRows().length} in package.json, ${WORKFLOW_STEPS.length} workflow steps — no drift`;

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  if (process.argv.includes('--check')) {
    report('check:check-registry', run(), { remedy: REMEDY, summary: summary() });
  } else {
    const written = [];
    for (const { file, content } of artifacts()) {
      if (read(file) === content) continue;
      fs.writeFileSync(path.join(REPO_ROOT, file), content);
      written.push(file);
      console.log(`[write] ${file}`);
    }
    if (!written.length) console.log('[ok] every generated block already matches the registry');
    const found = consistencyFindings();
    if (found.length) report('check:check-registry', found, { remedy: REMEDY });
    console.log(`[ok] ${summary()}`);
  }
}
