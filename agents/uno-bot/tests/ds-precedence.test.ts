interface Post {
  text: string;
  blocks?: unknown[];
  thread_ts?: string;
}

function postDeps(report: PrecedenceReport | null, openIntake: { number: number; url: string } | null) {
  const posts: Post[] = [];
  const staged: PendingProposal[] = [];
  const reportBox = kv<PrecedenceReport | null>(report);
  const threadBox = kv<PostedThread | null>(null);
  let n = 0;
  const deps: PostDeps = {
    report: reportBox.store,
    thread: threadBox.store,
    members: async () => [...MEMBERS],
    openIntake: async () => openIntake,
    post: async (message) => {
      posts.push(message);
      n += 1;
      return { ok: true, ts: `1759500000.00000${n}` };
    },
    stage: async (proposal) => {
      staged.push(proposal);
    },
    channel: CHANNEL,
    now: () => Date.UTC(2026, 9, 5, 14, 0),
  };
  return { deps, posts, staged, reportBox, threadBox };
}

describe("the end-of-day check", () => {
  it("keeps the disagreements for the morning", async () => {
    const { deps, report } = checkDeps(LIBRARY);
    const result = await runPrecedenceCheck(deps);
    assert.equal(result.found, 2);
    assert.deepEqual(report.box.value?.items.map((i) => i.component), ["Button", "TreeSelect"]);
  });

  it("a clean week keeps nothing, and clears a report nobody posted", async () => {
    const stale = kv<PrecedenceReport | null>({ checkedAt: "x", items: [] as PrecedenceReport["items"] } as PrecedenceReport);
    const { deps, report } = checkDeps(AGREEING, stale);
    const result = await runPrecedenceCheck(deps);
    assert.equal(result.found, 0);
    assert.equal(report.box.value, null);
  });

  it("an empty or near-empty library skips the week rather than reporting every component missing", async () => {
    // Nothing at all, and one set for three indexed components.
    for (const components of [[], LIBRARY.meta!.components!.slice(0, 1)]) {
      const stale = kv<PrecedenceReport | null>({ checkedAt: "x", items: [] } as unknown as PrecedenceReport);
      const { deps, report } = checkDeps({ meta: { components } }, stale);
      const result = await runPrecedenceCheck(deps);
      assert.equal(result.found, 0);
      assert.match(result.summary, /week skipped/);
      assert.equal(report.box.value, null, "nothing is kept for the morning, so nothing posts");
    }
  });

  it("a dry run compares and writes nothing", async () => {
    const { deps, report } = checkDeps(LIBRARY);
    await runPrecedenceCheck(deps, { dryRun: true });
    assert.equal(report.box.writes, 0);
  });
});

