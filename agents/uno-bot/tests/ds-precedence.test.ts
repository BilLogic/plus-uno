    await postPrecedenceReport(deps);
    const ops = staged[0]!.operations!;
    assert.equal(ops.length, 1);
    assert.equal(ops[0]!.toolName, "github_issue_update");
    assert.equal(ops[0]!.input.issue_number, 900);
