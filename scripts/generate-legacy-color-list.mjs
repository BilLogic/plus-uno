#!/usr/bin/env node
/**
 * `npm run generate:legacy-color-list` — the list of components still on
 * legacy color tokens, written into the color migration guide.
 *
 * The guide (`design-system/guidelines/foundations/color-migration.md`) is
 * what interns pick their next component from, so the list is generated from
 * source rather than kept by hand: a component leaves it the moment its last
 * legacy `var()` goes. The scan is `scripts/lib/color/legacy-components.mjs`;
 * this file renders the table and writes it between the guide's
 * `gen:LEGACY-COMPONENTS` markers, touching nothing else in the file.
 *
 * Usage:
 *   node scripts/generate-legacy-color-list.mjs           # write the list
 *   node scripts/generate-legacy-color-list.mjs --check   # CI: fail on drift
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { legacyComponents } from './lib/color/legacy-components.mjs';
import { isEntry, main } from './lib/findings.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const GUIDE = 'design-system/guidelines/foundations/color-migration.md';
const BEGIN = '<!-- gen:LEGACY-COMPONENTS -->';
const END = '<!-- /gen:LEGACY-COMPONENTS -->';

/** The table and its tally, between the markers. */
export function renderList({ root = ROOT } = {}) {
  const rows = legacyComponents({ root });
  const uses = rows.reduce((sum, r) => sum + r.uses, 0);
  const lines = [
    `${rows.length} components, ${uses} legacy uses. Generated by \`npm run generate:legacy-color-list\`; edit the components, not this table.`,
    '',
    '| Component | Uses | Legacy names |',
    '|---|---:|---|',
    ...rows.map((r) => `| \`${r.component}\` | ${r.uses} | ${r.names.length <= 3 ? r.names.map((n) => `\`${n}\``).join(' · ') : `${r.names.length} names`} |`),
  ];
  return `${BEGIN}\n${lines.join('\n')}\n${END}`;
}

/** The guide with its block replaced, or null when the markers are missing. */
export function updatedGuide({ root = ROOT } = {}) {
  const text = readFileSync(join(root, GUIDE), 'utf8').replace(/\r\n/g, '\n');
  const start = text.indexOf(BEGIN);
  const stop = text.indexOf(END);
  if (start < 0 || stop < start) return { text, next: null };
  return { text, next: text.slice(0, start) + renderList({ root }) + text.slice(stop + END.length) };
}

/** The drift check. Reports and never writes. */
export function run({ repoRoot = ROOT } = {}) {
  const { text, next } = updatedGuide({ root: repoRoot });
  if (next === null) return [{ file: GUIDE, message: `is missing the ${BEGIN} … ${END} markers` }];
  if (next !== text) return [{ file: GUIDE, message: 'legacy component list is stale — run: npm run generate:legacy-color-list' }];
  return [];
}

export const summary = () => `${legacyComponents({ root: ROOT }).length} components on legacy color tokens, listed in ${GUIDE}`;

if (isEntry(import.meta.url)) {
  if (process.argv.includes('--check')) {
    main(import.meta.url, 'check:legacy-color-list', { run, summary });
  } else {
    const { text, next } = updatedGuide();
    if (next === null) {
      console.error(`✗ ${GUIDE} is missing the ${BEGIN} … ${END} markers`);
      process.exit(1);
    }
    if (next !== text) {
      writeFileSync(join(ROOT, GUIDE), next);
      console.log(`[write] ${GUIDE}`);
    }
    console.log(`[ok] ${summary()}`);
  }
}
