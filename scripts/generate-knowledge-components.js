/**
 * Generate the component and forms existence indexes under
 * design-system/agent-views/.
 *
 *   components/index.md  ↔  src/components/index.js exports
 *   forms/index.md       ↔  redirect (src/forms/ was folded into components/)
 *
 * These are the existence law AGENTS.md cites: if a component is not listed
 * here, it does not exist. Nothing per-component is written — the 56 skeletons
 * this script used to emit were deleted in #156, and the generated component
 * half returns under #165 derived from source.
 *
 * Usage:
 *   node scripts/generate-knowledge-components.js
 *   node scripts/generate-knowledge-components.js --check  (CI: fail if stale, write nothing)
 */

import fs from 'fs';
import path from 'path';
import { AGENT_ROOT, REPO_ROOT } from './agent-views-paths.js';
import { checkArtifacts, writeArtifacts } from './lib/generated-artifact.js';

const COMPONENTS_INDEX = path.join(REPO_ROOT, 'design-system/src/components/index.js');

/** Resolve an import specifier (`@/components/x`, `./x`) to a barrel file. */
function resolveBarrel(spec, fromFile) {
  const base = spec.startsWith('@/')
    ? path.join(REPO_ROOT, 'design-system/src', spec.slice(2))
    : path.resolve(path.dirname(fromFile), spec);
  for (const candidate of [base, `${base}.js`, path.join(base, 'index.js')]) {
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  }
  return null;
}

/**
 * Every component name a barrel exports, following `export * from` one barrel at
 * a time.
 *
 * The star form is not cosmetic: `components/index.js` re-exports the whole
 * `forms-and-inputs` group that way, so a named-export-only regex silently
 * dropped DatePicker and InputGroup — real, documented, exported components —
 * from an index whose own header says "If it's not listed, it DOES NOT EXIST."
 * A generator that quietly under-reports is worse than one that fails.
 */
function extractExports(indexPath, seen = new Set()) {
  if (!fs.existsSync(indexPath) || seen.has(indexPath)) return [];
  seen.add(indexPath);
  const content = fs.readFileSync(indexPath, 'utf8');
  const names = [];

  const named = /export\s+\{.*as\s+([a-zA-Z0-9]+)\s*\}/g;
  let m;
  while ((m = named.exec(content)) !== null) names.push(m[1]);

  // Follow `export *` only into sibling barrels under the same root. This index
  // "mirrors design-system/src/components/" — `components/index.js` also stars
  // `@/dataviz`, and pulling 47 chart wrappers in here would file them under
  // "UI components". Charts have their own home in the IA.
  const root = path.dirname(indexPath).startsWith(path.join(REPO_ROOT, 'design-system/src/components'))
    ? path.join(REPO_ROOT, 'design-system/src/components')
    : path.dirname(indexPath);
  const star = /export\s+\*\s+from\s+['"]([^'"]+)['"]/g;
  while ((m = star.exec(content)) !== null) {
    const barrel = resolveBarrel(m[1], indexPath);
    if (!barrel) {
      console.warn(`  ! export * from '${m[1]}' in ${path.relative(REPO_ROOT, indexPath)} — unresolvable; its components would be MISSING from the index`);
      continue;
    }
    if (!barrel.startsWith(root)) continue; // e.g. @/dataviz — a different section
    names.push(...extractExports(barrel, seen));
  }

  return [...new Set(names)].sort();
}

/**
 * `export { default as Scale } from './RadioButtonGroup'` — the barrels alias
 * some exports onto another component. An agent that treats an alias as a
 * separate component writes code against props that belong to something else,
 * so the index names the target rather than hiding the indirection.
 */
function aliasTargets() {
  const root = path.join(REPO_ROOT, 'design-system/src/components');
  const map = {};
  for (const group of fs.readdirSync(root)) {
    const barrel = path.join(root, group, 'index.js');
    if (!fs.existsSync(barrel)) continue;
    const src = fs.readFileSync(barrel, 'utf8');
    for (const m of src.matchAll(/export\s*\{\s*default\s+as\s+(\w+)\s*\}\s*from\s*['"]\.\/(\w+)['"]/g)) {
      if (m[1] !== m[2]) map[m[1]] = m[2];
    }
  }
  return map;
}

/** Repo-relative path of a component's generated doc, or null if it has none. */
function generatedDocFor(name) {
  const root = path.join(REPO_ROOT, 'design-system/src/components');
  for (const group of fs.readdirSync(root)) {
    const groupDir = path.join(root, group);
    if (!fs.statSync(groupDir).isDirectory()) continue;
    for (const candidate of [path.join(groupDir, name, 'index.md'), path.join(groupDir, `${name}.md`)]) {
      if (fs.existsSync(candidate)) {
        // relative to the index that will carry the link, so it resolves on
        // GitHub and on disk alike
        return path.relative(path.join(AGENT_ROOT, 'components'), candidate).replace(/\\/g, '/');
      }
    }
  }
  return null;
}

function renderComponentIndex(components) {
  const aliases = aliasTargets();
  let doc = `<!-- DO NOT EDIT BY HAND. Generated by npm run generate:agent -->\n`;
  doc += `<!-- Load when: building UI | Route: design-system/guidelines/overview.md -->\n`;
  doc += `# PLUS DS — Components\n\n`;
  doc += `> **CRITICAL**: Only use components listed here. If it's not listed, it DOES NOT EXIST.\n\n`;
  doc += `Mirrors \`design-system/src/components/\`. Import via \`@/components/\`.\n\n`;
  doc += `This index is the existence list. Each entry links to its generated doc — `;
  doc += `props, variants, tokens touched — derived from source.\n\n`;
  doc += `## UI components (${components.length})\n\n`;
  doc += components
    .map((name) => {
      const generated = generatedDocFor(name);
      if (generated) return `- [${name}](${generated})`;
      const target = aliases[name];
      const viaAlias = target && generatedDocFor(target);
      if (viaAlias) return `- [${name}](${viaAlias}) — alias of \`${target}\`, same props`;
      return `- ${name} — exported here, implemented outside \`src/components/\`; read the source`;
    })
    .join('\n') + '\n';
  return doc;
}

function renderFormsIndex() {
  // `src/forms/` was folded into `src/components/forms-and-inputs/` in the
  // 2026-07 IA reorg, and three docs still route agents to this file. It has no
  // inventory to mirror any more, so a pointer is the only honest output — and
  // the only one this generator can emit without inventing a dead `@/forms/`
  // import surface.
  let doc = `<!-- DO NOT EDIT BY HAND. Generated by npm run generate:agent -->\n`;
  doc += `<!-- Load when: building forms | Route: design-system/guidelines/overview.md -->\n`;
  doc += `# PLUS DS — Forms\n\n`;
  doc += `> Form components moved into \`design-system/src/components/forms-and-inputs/\` (2026-07 IA reorg) and are listed in **[components/index.md](../components/index.md)**. Import them from \`@/components\` like any other component.\n\n`;
  doc += `\`design-system/src/forms/\` no longer exists. This file is a redirect, not an empty inventory — an absence here means nothing.\n`;
  return doc;
}

function renderReadme() {
  const doc = `# DO NOT EDIT BY HAND — generated by npm run generate:agent

Generated facts about \`design-system/src/\` — what exists and what it is named.
Nothing here is authored, and nothing here explains a component.

| File | Generated from | Answers |
|------|----------------|---------|
| \`components/index.md\` | \`src/components/index.js\` exports | Does this component exist? |
| \`forms/index.md\` | static redirect (\`src/forms/\` is gone) | Where did the form components go? |
| \`tokens/tokens.md\` | \`src/tokens/*.scss\` | What is this token called? |

For a component's props, variants and usage, read its Storybook MDX and
\`*.stories.jsx\`. There is no second corpus: the 56 per-component skeletons that
used to live here were deleted in #156 because they only ever said "see the
source", and the generated component half returns under #165 derived from source.

Regenerate: \`npm run generate:agent\`
`;
  return doc;
}

function main() {
  const check = process.argv.includes('--check');
  const components = extractExports(COMPONENTS_INDEX);

  const artifacts = [
    { file: path.join(AGENT_ROOT, 'components/index.md'), content: renderComponentIndex(components) },
    { file: path.join(AGENT_ROOT, 'forms/index.md'), content: renderFormsIndex(), note: '(redirect — src/forms/ is gone)' },
    { file: path.join(AGENT_ROOT, 'README.md'), content: renderReadme() },
  ];

  if (check) {
    if (!checkArtifacts(artifacts)) {
      console.error('  -> run `npm run generate:knowledge-components`');
      process.exit(1);
    }
    console.log(`✓ agent views (component + forms index) up to date (${components.length} components indexed)`);
    return;
  }

  writeArtifacts(artifacts);
  console.log(`Done. ${components.length} components indexed.`);
}

main();
