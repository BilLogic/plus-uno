#!/usr/bin/env node
/**
 * `npm run generate:legacy-color-list` — the list of components still on
 * legacy color tokens, written into the color migration guide.
 *
 * The guide (`design-system/guidelines/foundations/color-migration.md`) is
 * what interns pick their next component from, so the list is generated from
 * source rather than kept by hand: a component leaves it the moment its last
 * legacy `var()` goes. The scan is `scripts/lib/color/legacy-components.mjs`;
 * this file renders the table and writes it between the guide's
 * `gen:LEGACY-COMPONENTS` markers, touching nothing else in the file.
 *
 * `HOLDS` marks the components another piece of work owns, so an intern skips
 * them. A row leaves the table when its component is migrated, so a stale hold
 * goes with it; delete a hold once its work has landed.
 *
 * Usage:
 *   node scripts/generate-legacy-color-list.mjs           # write the list
 *   node scripts/generate-legacy-color-list.mjs --check   # CI: fail on drift
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { legacyComponents } from './lib/color/legacy-components.mjs';
import { byRoot, isEntry, main } from './lib/findings.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const GUIDE = 'design-system/guidelines/foundations/color-migration.md';
const BEGIN = '<!-- gen:LEGACY-COMPONENTS -->';
const END = '<!-- /gen:LEGACY-COMPONENTS -->';
const REMEDY = 'Run `npm run generate:legacy-color-list` and commit the guide.';

/** Who holds a component, first match wins; a component no row matches is "take". */
export const HOLDS = [
  { match: /^forms-and-inputs\/(Button|ButtonGroup|CloseButton)$/, status: 'held: Button refresh (Cynthia)' },
  { match: /^forms-and-inputs\//, status: 'held: Forms & Inputs colors in flight; shape with the Button refresh' },
  { match: /^(navigation\/SidebarTab|_internal\/Sidebar)$/, status: 'held: frame chain' },
  { match: /^(messaging\/(Modal|Toast)|overlays-and-layering\/(Popover|Tooltip))$/, status: 'held: layers' },
  { match: /^(labels\/(Tag|Suggestion)|navigation\/NavTabs|_internal\/StaticBadgeSmart)$/, status: 'held: tags, SMART, Suggestion, NavTabs' },
  { match: /^_internal\//, status: 'take: internal composite; verify in the stories that render it' },
];

export const statusOf = (component) => HOLDS.find((h) => h.match.test(component))?.status ?? 'take';

const namesCell = (names) => (names.length <= 3 ? names.map((n) => `\`${n}\``).join(' · ') : `${names.length} names`);

const scan = byRoot((repoRoot) => legacyComponents({ root: repoRoot }));

/** The table and its tally, between the markers. */
export function renderList(rows) {
  const uses = rows.reduce((sum, r) => sum + r.uses, 0);
  const lines = [
    `${rows.length} components, ${uses} legacy uses. Generated by \`npm run generate:legacy-color-list\`; edit the components or \`HOLDS\` in that script, not this table.`,
    '',
    '| Component | Uses | Legacy names | Status |',
    '|---|---:|---|---|',
    ...rows.map((r) => `| \`${r.component}\` | ${r.uses} | ${namesCell(r.names)} | ${statusOf(r.component)} |`),
  ];
  return `${BEGIN}\n${lines.join('\n')}\n${END}`;
}

/** The guide text, and the text it should be (null when the markers are missing). */
export function guideUpdate(text, rows) {
  const current = text.replace(/\r\n/g, '\n');
  const start = current.indexOf(BEGIN);
  const stop = current.indexOf(END);
  if (start < 0 || stop < start) return { current, next: null };
  return { current, next: current.slice(0, start) + renderList(rows) + current.slice(stop + END.length) };
}

const readGuide = (repoRoot) => guideUpdate(readFileSync(join(repoRoot, GUIDE), 'utf8'), scan(repoRoot));

/** The drift check. Reports and never writes. */
export function run({ repoRoot = ROOT } = {}) {
  const { current, next } = readGuide(repoRoot);
  if (next === null) return [{ file: GUIDE, message: `is missing the ${BEGIN} … ${END} markers` }];
  if (next !== current) return [{ file: GUIDE, message: 'the legacy component list is stale' }];
  return [];
}

export const summary = ({ repoRoot = ROOT } = {}) =>
  `${scan(repoRoot).length} components on legacy color tokens, listed in ${GUIDE}`;

if (isEntry(import.meta.url)) {
  if (process.argv.includes('--check')) {
    main(import.meta.url, 'check:legacy-color-list', { run, summary, remedy: REMEDY });
  } else {
    const { current, next } = readGuide(ROOT);
    if (next === null) {
      console.error(`✗ ${GUIDE} is missing the ${BEGIN} … ${END} markers`);
      process.exit(1);
    }
    if (next !== current) {
      writeFileSync(join(ROOT, GUIDE), next);
      console.log(`[write] ${GUIDE}`);
    }
    console.log(`[ok] ${summary()}`);
  }
}
