/**
 * How `generate-component-docs.mjs` reads an enum named by a constant, and the
 * render it writes every doc with (`lib/component-render.mjs`), on fixtures.
 * That `ds_get` returns the written file byte for byte is held in
 * `lib/ds-lookup.test.mjs`.
 *
 * The generator runs on import, so it cannot be imported here. It reads a
 * named enum through `resolveNamedOneOf` and `namedEnumValues` in
 * `doc-identifiers.mjs`, the same reader `check:doc-identifiers` uses, and
 * that is what these tests hold. `check:component-docs` then compares the
 * committed pages with a fresh run.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';

import { namedEnumValues, resolveNamedOneOf } from './doc-identifiers.mjs';
import { componentFacts, docPathOf, renderComponent } from './lib/component-render.mjs';
import { readDocsPage } from './lib/docs-page.mjs';

test('a plain array of strings is read in order', () => {
  const source = "export const STYLES = ['primary', 'success'];\n";
  assert.deepEqual(namedEnumValues(source, 'STYLES'), ['primary', 'success']);
  assert.equal(
    resolveNamedOneOf('PropTypes.oneOf(STYLES)', source),
    "PropTypes.oneOf(['primary', 'success'])",
  );
});

test('double quotes read the same as single quotes', () => {
  const source = 'const KINDS = ["state", \'date\'];\n';
  assert.deepEqual(namedEnumValues(source, 'KINDS'), ['state', 'date']);
});

test('an array with a spread stays unresolved rather than listing part of it', () => {
  // Tag: `TAG_TYPES = ['plain', ...AVATAR_TAG_TYPES]`. Reading only the
  // literals documented `plain` as the one legal type.
  const source = "const AVATAR = ['person', 'agent', 'team'];\nconst TYPES = ['plain', ...AVATAR];\n";
  assert.equal(namedEnumValues(source, 'TYPES'), null);
  assert.equal(resolveNamedOneOf('PropTypes.oneOf(TYPES)', source), 'PropTypes.oneOf(TYPES)');
});

test('any element that is not a string or number literal stays unresolved', () => {
  assert.equal(namedEnumValues("const X = ['a', OTHER];", 'X'), null);
  assert.equal(namedEnumValues("const X = ['a', `b`];", 'X'), null);
});

test('a numeric array lists its numbers', () => {
  const source = 'export const SIZES = [16, 20, 24];\n';
  assert.deepEqual(namedEnumValues(source, 'SIZES'), ['16', '20', '24']);
  assert.equal(resolveNamedOneOf('PropTypes.oneOf(SIZES)', source), 'PropTypes.oneOf([16, 20, 24])');
});

test('every named oneOf in a type is resolved, not only the first', () => {
  const source = "const A = ['a'];\nconst B = ['b'];\n";
  assert.equal(
    resolveNamedOneOf('PropTypes.oneOfType([PropTypes.oneOf(A), PropTypes.oneOf(B)])', source),
    "PropTypes.oneOfType([PropTypes.oneOf(['a']), PropTypes.oneOf(['b'])])",
  );
});

test('a constant from another module stays as written', () => {
  assert.equal(resolveNamedOneOf('PropTypes.oneOf(SIZES)', 'import { SIZES } from "./s";'), 'PropTypes.oneOf(SIZES)');
});

// ── the render: one text for the generated file and ds_get ─────────────────

const FIXTURE_PAGE = `import { Meta } from '@storybook/blocks';
export const figmaMeta = {"fileKey": "abc123", "sets": [{"name": "Widget", "componentSetNodeId": "1:2", "url": "https://www.figma.com/design/abc123/x?node-id=1-2"}]};

<Meta title="Widget" />

## Usage

Use \`Widget\` to show one thing.

## Alternatives

- For a short notice, use \`Flag\`.

## Best practices

### Keep it short.

One line.

Do: One line.
Don't: Three paragraphs.

## Accessibility

- **It has a name.**

## Related

- \`Gadget\` — when there are two things.
`;

const FIXTURE_MANIFEST = {
  version: '0',
  components: [
    {
      name: 'Widget',
      kind: 'component',
      import: "import { Widget } from '@/components';",
      group: 'misc',
      source: 'design-system/src/components/misc/Widget/Widget.jsx',
      summary: 'Widget: one thing on its own.',
      props: [
        { name: 'tone', type: 'enum', required: false, default: "'calm'", values: ['calm', 'loud'], description: 'How loud it is.', deprecated: null },
        { name: 'onPick', type: 'func', required: true, default: null, values: null, description: null, deprecated: null },
      ],
      stories: ['Default', 'Loud'],
      tokens: ['--ds-text', '--widget-pad'],
    },
    { name: 'Gadget', kind: 'component', import: "import { Gadget } from '@/components';", group: 'misc', source: 'x/Gadget/Gadget.jsx', summary: null, props: [] },
    { name: 'PatternThing', kind: 'pattern', import: "import { PatternThing } from '@/patterns';", group: 'misc', source: 'p/PatternThing/PatternThing.jsx', summary: null, props: [] },
  ],
};

test('the render carries the facts, the Usage spine, Alternatives and rules with ids', () => {
  const text = renderComponent(componentFacts(FIXTURE_MANIFEST, 'Widget'), { path: 'design-system/src/components/misc/Widget/Widget.mdx', page: readDocsPage(FIXTURE_PAGE) });
  assert.match(text, /^<!-- DO NOT EDIT BY HAND\. Generated by npm run generate:component-docs -->\n/);
  assert.match(text, /\n# Widget\n\nWidget: one thing on its own\.\n/);
  assert.match(text, /\*\*Import:\*\* `import \{ Widget \} from '@\/components';`/);
  assert.match(text, /\*\*Stories:\*\* `[^`]+Widget\.stories\.jsx` — Default, Loud/);
  assert.match(text, /## Usage\n\nUse `Widget` to show one thing\./);
  assert.match(text, /## Alternatives\n\n- For a short notice, use `Flag`\./);
  assert.match(text, /### Keep it short\. \{#keep-it-short\}\n\nOne line\./);
  assert.match(text, /## Accessibility\n\n- \*\*It has a name\.\*\*/);
  assert.match(text, /\| `tone` \| enum \| `'calm'` \| How loud it is\. \|/);
  assert.match(text, /\| `onPick` \| func \(required\) \| — \| — \|/);
  assert.match(text, /\*\*`tone`\*\* — `calm` · `loud`/);
  assert.match(text, /## Tokens touched\n\n`--ds-text` · `--widget-pad`/);
  assert.match(text, /- "Widget" node 1:2 in file abc123/);
  assert.match(text, /- `Gadget` — when there are two things\.\n\nSame group: `Gadget`\n/);
  assert.match(text, /<!-- authored coverage: whenToUse=yes correctIncorrect=yes accessibility=yes -->\n$/);
  // the file obeys the docs rules: no raw Figma URL, no tool hints, no issue numbers
  assert.doesNotMatch(text, /figma\.com|Next:|#\d{2,}/);
});

test('the render follows the Usage spine, then Parts and Content guidelines, then the facts', () => {
  const page = readDocsPage(`## Usage\n\nUse it.\n\n## Alternatives\n\n- For a notice, use \`Flag\`.\n\n## Parts\n\n1. **Box.**\n\n### States\n\n| State | What changes |\n| --- | --- |\n| Rest | Nothing. |\n\n## Best practices\n\n### Keep it short.\n\nOne line.\n\n## Content guidelines\n\nSay what happens.\n\n## Accessibility\n\nIt has a name.\n\n## Related\n\n- \`Gadget\`: use when there are two.\n`);
  const text = renderComponent(componentFacts(FIXTURE_MANIFEST, 'Widget'), { path: 'w.mdx', page });
  const order = [...text.matchAll(/^## (.*)$/gm)].map((m) => m[1]);
  assert.deepEqual(order, ['Usage', 'Alternatives', 'Best practices', 'Accessibility', 'Related', 'Parts', 'Content guidelines', 'Props', 'Variants', 'Tokens touched']);
  assert.match(text, /## Parts\n\n1\. \*\*Box\.\*\*\n\n### States\n\n\| State \| What changes \|/);
  assert.doesNotMatch(text, /not listed is not a valid value/);
});

test('once a page tags a rule, every rule carries its Checked line, untagged ones reading Review', () => {
  const page = readDocsPage(`## Usage\n\nUse it.\n\n## Best practices\n\n### Keep it short.\n\n<RuleTag kind="automatic" />\n\nOne line.\n\n### Say why.\n\nOne reason.\n`);
  const text = renderComponent(componentFacts(FIXTURE_MANIFEST, 'Widget'), { path: 'w.mdx', page });
  assert.match(text, /### Keep it short\. \{#keep-it-short\}\n\n\*\*Checked:\*\* Automatic\n\nOne line\./);
  assert.match(text, /### Say why\. \{#say-why\}\n\n\*\*Checked:\*\* Review\n\nOne reason\./);
});

test('a page with no rule tags renders its rules without Checked lines', () => {
  const text = renderComponent(componentFacts(FIXTURE_MANIFEST, 'Widget'), { path: 'w.mdx', page: readDocsPage(FIXTURE_PAGE) });
  assert.doesNotMatch(text, /\*\*Checked:\*\*/);
});

test('a template page\'s Slots table follows Parts, so an agent sees which slots are planned', () => {
  const page = readDocsPage(`## Usage\n\nUse it.\n\n## Slots\n\n| Slot | Holds |\n| --- | --- |\n| \`side\` Planned | A second column. |\n\n## Parts\n\n1. **Box.**\n`);
  const text = renderComponent(componentFacts(FIXTURE_MANIFEST, 'Widget'), { path: 'w.mdx', page });
  const order = [...text.matchAll(/^## (.*)$/gm)].map((m) => m[1]);
  assert.deepEqual(order.filter((t) => ['Usage', 'Parts', 'Slots'].includes(t)), ['Usage', 'Parts', 'Slots']);
  assert.match(text, /## Slots\n\n\| Slot \| Holds \|/);
});

test('a component with no page says its guidance is unwritten, and a pattern is not its sibling', () => {
  const text = renderComponent(componentFacts(FIXTURE_MANIFEST, 'Gadget'), null);
  assert.match(text, /No authored guidance yet/);
  assert.match(text, /Same group: `Widget`\n/);
  assert.doesNotMatch(text, /PatternThing|## Usage/);
});

test('a component in its own folder is written as index.md, a flat one as <Name>.md', () => {
  assert.equal(docPathOf({ name: 'Modal', source: 'a/messaging/Modal/Modal.jsx' }), 'a/messaging/Modal/index.md');
  assert.equal(docPathOf({ name: 'Fieldset', source: 'a/forms/Fieldset.jsx' }), 'a/forms/Fieldset.md');
  assert.equal(docPathOf({ name: 'PatternSidebar', source: 'p/Sidebar/Sidebar.jsx' }), 'p/Sidebar/index.md');
});
