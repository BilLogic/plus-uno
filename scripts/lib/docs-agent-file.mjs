/**
 * The generated agent file for a docs-only page: a template page or a pattern
 * page, which has no component to read props from, so its file is made from the
 * page alone.
 *
 *   docsAgentPages(root)                     [{ file, kind, title }]  every Templates/ and Patterns/ page
 *   renderDocsAgentFile(source, {file, kind})  the file's text
 *   agentFilePath(file)                      where that page's file lives
 *   pagesMissingManifestTag(root)            the pages the Storybook MCP would not serve
 *   syncDocsAgentFiles(root, {check})        write every file, or with `check` report the stale ones
 *
 * A page is a docs-only page when its `<Meta title>` sits under `Templates/` or
 * `Patterns/`. Its file is `design-system/agent-views/pages/<root>/<name>.md`,
 * beside the other generated agent views, so no MDX page carries agent text.
 *
 * What the file holds: the page's title and intro first, so the glossary term
 * leads; each Usage section as the page wrote it; each rule under Best
 * practices as a `###` sentence whose `{#slug}` is the rule id, with one line
 * saying how it is held: `Checked: Automatic` or `Checked: Review`. The tag is
 * the page's `<RuleTag kind="automatic|review" />` under the rule's heading; a
 * rule without one reads as Review, since nothing fails a build on it.
 */

import fs from 'node:fs';
import path from 'node:path';

import { pageText, pagesUnder, readDocsPage, ruleTags } from './docs-page.mjs';
import { motionRowOf, motionSectionOf } from './tokens/motion-docs.mjs';
import { MOTION_REGISTRY } from './tokens/motion-registry.mjs';

export const GENERATED_HEADER = '<!-- DO NOT EDIT BY HAND. Generated by npm run generate:docs-agent-files -->';
export const OUT_DIR = 'design-system/agent-views/pages';
const ROOTS = { Templates: 'templates', Patterns: 'patterns' };
const KINDS = { Templates: 'Template', Patterns: 'Pattern' };

/** The `<Meta title>` root a page sits under, or null. */
function rootOf(source) {
  const title = source.match(/<Meta\b[^>]*?\btitle=["']([^"']+)["']/)?.[1];
  const root = title?.split('/')[0];
  return root in ROOTS ? root : null;
}

/** The kind, Meta root and path of every template and pattern page, repo-relative. */
export function docsAgentPages(root) {
  const out = [];
  for (const file of pagesUnder(root)) {
    const source = fs.readFileSync(path.join(root, file), 'utf8');
    const top = rootOf(source);
    if (top) out.push({ file, root: top, kind: KINDS[top], title: source.match(/<Meta\b[^>]*?\btitle=["']([^"']+)["']/)[1] });
  }
  return out;
}

/** Where a page's agent file lives: `<out>/<root>/<Name>.md`, `Name` being the page's file name. */
export function agentFilePath(file, top) {
  return `${OUT_DIR}/${ROOTS[top]}/${path.basename(file, '.mdx')}.md`;
}

/** Each rule's tag by its id; the page model reads the same marker (`ruleTags` in `docs-page.mjs`). */
export { ruleTags };

/**
 * Pages the Storybook MCP would not serve: `get-documentation` lists a docs page
 * only when it carries the `manifest` tag, so a template or pattern page without
 * it is invisible to an agent that asks the endpoint.
 */
export function pagesMissingManifestTag(root) {
  return docsAgentPages(root)
    .filter((p) => {
      const tags = fs.readFileSync(path.join(root, p.file), 'utf8').match(/<Meta\b[^>]*?\btags=\{\[([^\]]*)\]\}/)?.[1] ?? '';
      return !/['"]manifest['"]/.test(tags);
    })
    .map((p) => p.file);
}

const label = (kind) => (kind === 'automatic' ? 'Automatic' : 'Review');

/** The file's text (see the header). */
export function renderDocsAgentFile(source, { file, kind, root, top, registry = MOTION_REGISTRY }) {
  const page = readDocsPage(source, { kind: 'foundation', root, file: root ? file : undefined });
  const tags = ruleTags(source);
  const best = page.sections.find((s) => s.title.toLowerCase() === 'best practices');
  // The Motion section is the registry row, written by `motionSectionOf` and never from the page's own text.
  const motionTag = source.match(/<MotionSection\b[^>]*?\bcomponent=["']([^"']+)["'](?:[^>]*?\btier=["']([^"']+)["'])?/);
  const others = page.sections.filter((s) => s !== best && !(motionTag && s.title === 'Motion'));
  let d = `${GENERATED_HEADER}\n\n# ${page.title}\n\n`;
  if (page.intro) d += `${page.intro}\n\n`;
  d += `**Kind:** ${kind}\n\n**Storybook page:** \`${file}\`\n\n`;
  const body = pageText({ ...page, title: null, intro: '', sections: others });
  if (body) d += `${body}\n\n`;
  if (motionTag) {
    const row = motionRowOf(motionTag[1], registry, motionTag[2] ?? null);
    if (!row) throw new Error(`${file}: <MotionSection component="${motionTag[1]}"> names no motion registry row`);
    d += motionSectionOf(row);
  }
  if (page.rules.length) {
    d += `## Best practices\n\n`;
    // What the section says before its first rule: a pointer to the pattern that owns the rules.
    const lead = best?.text?.split(/\n#{3} /)[0]?.trim();
    if (lead) d += `${lead}\n\n`;
    for (const r of page.rules) {
      d += `### ${r.sentence} {#${r.id}}\n\n**Checked:** ${label(tags[r.id] ?? 'review')}\n\n${r.text ? `${r.text}\n\n` : ''}`;
    }
  }
  return d.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

/**
 * Write every file, or with `check` write nothing and return the stale ones:
 * a file whose bytes differ from a fresh render, a page with no file, and a
 * file with no page (a rename leaves one behind).
 */
export function syncDocsAgentFiles(root, { check = false } = {}) {
  const stale = [];
  const wanted = new Set();
  for (const page of docsAgentPages(root)) {
    const out = agentFilePath(page.file, page.root);
    wanted.add(out);
    const text = renderDocsAgentFile(fs.readFileSync(path.join(root, page.file), 'utf8'), { file: page.file, kind: page.kind, root });
    const abs = path.join(root, out);
    const prev = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (prev === text) continue;
    if (check) stale.push(out);
    else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, text);
    }
  }
  const dir = path.join(root, OUT_DIR);
  if (fs.existsSync(dir)) {
    for (const sub of fs.readdirSync(dir)) {
      for (const f of fs.readdirSync(path.join(dir, sub))) {
        const rel = `${OUT_DIR}/${sub}/${f}`;
        if (wanted.has(rel)) continue;
        if (check) stale.push(rel);
        else fs.rmSync(path.join(root, rel));
      }
    }
  }
  return { stale, count: wanted.size };
}
