/**
 * The color pipeline in one call: plan -> primitive palette -> semantic layer
 * -> SCSS and Figma spec. The reference generator ran these as separate
 * scripts (build, plans, semantics, figma, emit) passing JSON files between
 * them; here they pass values, and nothing is written.
 */

import { REPO_ROOT } from '../corpus.mjs';
import { emitScss } from './emit.mjs';
import { figmaSpec } from './figma.mjs';
import { PLAN_KEYS, buildPalette, loadPlan, planFile } from './plans.mjs';
import { buildSemantics, loadAtlassian } from './semantics.mjs';

/** One plan, built from the inputs under `root`. Memoized per root: they do not change within a process. */
const built = new Map();
export function buildPlan(key, { root = REPO_ROOT } = {}) {
  const id = `${root}\0${key}`;
  if (!built.has(id)) {
    const plan = loadPlan(key, { root });
    built.set(id, { plan, semantics: buildSemantics(buildPalette(plan), loadAtlassian({ root })) });
  }
  return built.get(id);
}

/** Every plan, built, keyed by plan key. */
export const buildAllPlans = (options) => Object.fromEntries(PLAN_KEYS.map((key) => [key, buildPlan(key, options)]));

/**
 * The generated files for one plan, rendered and not written.
 *
 * @param {string} key
 * @param {string} generator  repo path of the script that writes them, named in each file's header
 * @returns {Record<string, string>} file name -> contents
 */
export function renderPlan(key, generator) {
  const { semantics } = buildPlan(key);
  const note = `GENERATED by ${generator} from ${planFile(key)} (Plan ${key}). Do not edit; change the plan or the generator and run \`npm run generate:color-tokens\`.`;
  const files = emitScss(semantics, `// ${note}\n`);
  // JSON has no comments, so the header rides as the spec's first key; a Figma push script ignores it.
  files['figma-spec.json'] = `${JSON.stringify({ $generated: note, ...figmaSpec(key, semantics) }, null, 1)}\n`;
  return files;
}
