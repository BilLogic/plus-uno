#!/usr/bin/env node
// Bakes the design-system facts into the Worker (src/generated/ds-facts.ts),
// from the root facts module (`scripts/lib/ds-facts.mjs`).
//
// WHY. The IDE answers "does PLUS have a card?" from the facts module:
// `PatternCard`, with its import. The Worker answered it by reading the
// markdown index over GitHub and parsing it with a regex, so Slack and the IDE
// could disagree, and every read cost a subrequest of the 50 a turn on Workers
// Free has (`net.ts`). Baked, `github_read`'s `lookup` and the weekly
// precedence check read the same facts the IDE does, with no fetch at all.
//
// WHAT IS KEPT. Only what the bot answers with: each component's and pattern's
// kind, import, group, summary, source, generated doc and props (name, type,
// values, default, whether required, a deprecation); each token's tier, group,
// value and intent; the names each public barrel exports; and the names that
// are not here, with what to use instead. Prop descriptions stay in the
// generated docs `github_read` reads by path. Every answer is the facts
// module's own, so the in-Worker lookup (`src/integrations/ds-facts.ts`)
// returns what the root module returns for the same name.
//
// WHEN. The deploy chain runs this before it typechecks, as it runs the
// Storybook docs map, so the Worker deployed is the facts on main at deploy.
// The committed copy is there for the typecheck and the tests; `--check` says
// whether it still matches.
//
// Run: npm run generate:ds-facts  (`-- --check` to compare only)

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(process.env.PLUS_UNO_ROOT ?? resolve(HERE, "../../.."));
const OUT = "agents/uno-bot/src/generated/ds-facts.ts";
const COMPONENTS_DIR = "design-system/src/components";

/** Drop the fields that say nothing: null, undefined, false and empty lists. */
function compact(record) {
  return Object.fromEntries(
    Object.entries(record).filter(([, v]) => v !== null && v !== undefined && v !== false && !(Array.isArray(v) && !v.length)),
  );
}

/**
 * A component's generated doc, repo-relative, found by name the way the
 * component index finds it: `<group>/<Name>/index.md`, or `<group>/<Name>.md`
 * for a component filed flat. Null when it has none.
 */
export function generatedDocFor(root, name) {
  const base = join(root, COMPONENTS_DIR);
  if (!existsSync(base)) return null;
  for (const group of readdirSync(base).sort()) {
    const groupDir = join(base, group);
    if (!statSync(groupDir).isDirectory()) continue;
    for (const candidate of [join(groupDir, name, "index.md"), join(groupDir, `${name}.md`)]) {
      if (existsSync(candidate)) return relative(root, candidate).split("\\").join("/");
    }
  }
  return null;
}

/**
 * The baked facts, as the in-Worker lookup reads them.
 *
 * @param {ReturnType<import('../../../scripts/lib/ds-facts.mjs').loadFacts>} facts
 * @param {{ docFor?: (name: string) => string | null, inventions: { components: object[], props: object[], tokens: object[] } }} opts
 */
export function bakeFacts(facts, { docFor = () => null, inventions }) {
  const components = facts.manifests.components.components.map(({ name }) => {
    const a = facts.lookup(name);
    return compact({
      name,
      kind: a.kind,
      import: a.import,
      group: a.group,
      source: a.source,
      doc: a.kind === "component" ? docFor(name) : null,
      summary: a.summary,
      aliasOf: a.aliasOf,
      props: (a.props ?? []).map((p) =>
        compact({ name: p.name, type: p.type, values: p.values, default: p.default, required: p.required === true, deprecated: p.deprecated }),
      ),
    });
  });
  const groups = [...new Set(facts.manifests.tokens.tokens.map((t) => t.group))];
  const row = (r) => compact({ not: r.not, use: [...r.use], why: r.why ?? null });
  return {
    components,
    barrels: Object.fromEntries(Object.entries(facts.barrels).map(([spec, names]) => [spec, [...names].sort()])),
    tokenGroups: groups,
    // [name, tier, group index, value, intent]: 1,400 records, so a tuple.
    tokens: facts.manifests.tokens.tokens.map((t) => [t.name, t.tier, groups.indexOf(t.group), t.value, t.intent ?? null]),
    inventions: {
      components: inventions.components.map(row),
      props: inventions.props.map(row),
      tokens: inventions.tokens.map(row),
    },
    retired: [...facts.retired],
  };
}

/** The generated module's text. */
export function renderDsFacts(baked) {
  return (
    "// GENERATED by scripts/generate-ds-facts.mjs from the DS facts module (scripts/lib/ds-facts.mjs)\n" +
    "// — do not edit by hand. Run: npm run generate:ds-facts\n" +
    "// Read by src/integrations/ds-facts.ts.\n" +
    'import type { BakedDsFacts } from "../integrations/ds-facts";\n\n' +
    `export const DS_FACTS: BakedDsFacts = ${JSON.stringify(baked)};\n`
  );
}

async function main() {
  const check = process.argv.includes("--check");
  const { loadFacts } = await import(pathToFileURL(join(ROOT, "scripts/lib/ds-facts.mjs")).href);
  const facts = loadFacts(ROOT);
  const inventions = JSON.parse(readFileSync(join(ROOT, "design-system/agent-views/_inventions.json"), "utf8"));
  const text = renderDsFacts(bakeFacts(facts, { docFor: (name) => generatedDocFor(ROOT, name), inventions }));
  const out = resolve(ROOT, OUT);
  const committed = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (check) {
    if (committed !== text) {
      console.error(`${OUT} is stale: run npm run generate:ds-facts`);
      process.exit(1);
    }
    console.log(`${OUT} is current`);
    return;
  }
  if (committed !== text) writeFileSync(out, text, "utf8");
  console.log(`${OUT}: ${text === committed ? "unchanged" : "written"} (${text.length} chars)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
